static PxValue rsi_next(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    PxIterObj *it = px_is_obj(t) && px_type_of(t) == PX_T_ITEROBJ ? (PxIterObj *)px_ptr(t) : NULL;
    PxValue    R, S, res = PX_UNDEFINED, r = PX_EXCEPTION;
    int32_t    local[16], *caps = NULL;
    uint32_t   nr = vm->nroots, flags;
    int        m, e;
    (void)argc;
    (void)argv;
    if (!it || it->kind != PX_IT_REGEXP_STRING)
        return px_throw_error(vm, PX_TYPE_ERROR, "%%RegExpStringIteratorPrototype%%.next called on an incompatible receiver");
    if (it->done) return px_iter_result(vm, PX_UNDEFINED, 1);
    R     = ((PxVec *)px_ptr(it->target))->items[0];
    S     = ((PxVec *)px_ptr(it->target))->items[1];
    flags = it->index;
    PX_ROOT(vm, t);
    PX_ROOT(vm, R);
    PX_ROOT(vm, S);
    PX_ROOT(vm, res);
    if (!(caps = caps_for(vm, R, local, 16)) || (m = regexp_exec(vm, R, S, caps, &res)) < 0) goto out;
    if (m == 0) {
        ((PxIterObj *)px_ptr(t))->done = 1;
        r                              = px_iter_result(vm, PX_UNDEFINED, 1);
        goto out;
    }
    if (flags & 1) {
        if ((e = match_empty(vm, res, caps)) < 0 || (e && step_last_index(vm, R, S, (flags & 2) != 0) < 0)) goto out;
    } else {
        ((PxIterObj *)px_ptr(t))->done = 1;
    }
    if (res == PX_UNDEFINED && (res = make_result(vm, R, S, caps)) == PX_EXCEPTION) goto out;
    r = px_iter_result(vm, res, 0);
out:
    if (caps) CAPS_FREE(caps, local);
    vm->nroots = nr;
    return r;
}

/* get RegExp[Symbol.species]() { return this } */
static PxValue regexp_species(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    (void)vm;
    (void)argc;
    (void)argv;
    return t;
}

/* ------------------------------------------------------------ String methods */

static int64_t str_index_of(const PxString *s, const PxString *p, uint32_t from) {
    uint32_t i, j;
    for (i = from; i + p->len <= s->len; i++) {
        for (j = 0; j < p->len && px_str_at(s, i + j) == px_str_at(p, j); j++) {}
        if (j == p->len) return i;
    }
    return -1;
}

/* String.prototype.replace / replaceAll with a string pattern (22.1.3.19, 22.1.3.20). */
static PxValue string_replace(PxVM *vm, PxValue S, PxValue sv, PxValue rv, int all) {
    uint32_t  nr = vm->nroots, end = 0, k, npos = 0, cap = 0, *pos = NULL;
    PxValue   r = PX_EXCEPTION;
    PxString *s, *p;
    Piece     pc = {PX_UNDEFINED, PX_UNDEFINED, PX_UNDEFINED, 0};
    U16Buf    b  = {0};
    int64_t   at;
    PX_ROOT(vm, S);
    PX_ROOT(vm, rv);
    if ((sv = px_to_string(vm, sv)) == PX_EXCEPTION) goto out;
    PX_ROOT(vm, sv);
    if (!px_is_callable(rv) && (rv = px_to_string(vm, rv)) == PX_EXCEPTION) goto out;
    if (!(s = px_str_flat(vm, S)) || !(p = px_str_flat(vm, sv))) goto out;
    for (at = str_index_of(s, p, 0); at >= 0; at = str_index_of(s, p, (uint32_t)at + (p->len ? p->len : 1))) {
        if (npos == cap) {
            uint32_t *np = (uint32_t *)realloc(pos, (cap = cap * 2 + 4) * sizeof(uint32_t));
            if (!np) {
                px_throw_oom(vm);
                goto out;
            }
            pos = np;
        }
        pos[npos++] = (uint32_t)at;
        if (!all || at >= s->len) break;
    }
    if (npos == 0) {
        r = S;
        goto out;
    }
    pc.matched = sv;
    PX_ROOT(vm, pc.caps);
    if ((pc.caps = px_array_new(vm, 0)) == PX_EXCEPTION) goto out;
    for (k = 0; k < npos; k++) {
        s = px_str_flat(vm, S);
        ub_range(&b, s, end, pos[k]);
        pc.pos = pos[k];
        if (replace_piece(vm, &b, &pc, S, rv) < 0) goto out;
        end = pos[k] + px_str_len(sv);
    }
    s = px_str_flat(vm, S);
    ub_range(&b, s, end, s->len);
    r   = ub_finish(vm, &b);
    b.d = NULL;
out:
    free(b.d);
    free(pos);
    vm->nroots = nr;
    return r;
}

/* String.prototype.split with a string separator (22.1.3.23). */
static PxValue string_split(PxVM *vm, PxValue S, PxValue sep, PxValue limit) {
    uint32_t  nr = vm->nroots, lim = 0xFFFFFFFFu, i = 0;
    PxValue   A = PX_UNDEFINED, R, v, r = PX_EXCEPTION;
    PxString *s, *p;
    int64_t   j;
    PX_ROOT(vm, S);
    PX_ROOT(vm, A);
    if (limit != PX_UNDEFINED && px_to_uint32(vm, limit, &lim) < 0) goto out;
    if ((R = px_to_string(vm, sep)) == PX_EXCEPTION) goto out;
    PX_ROOT(vm, R);
    if ((A = px_array_new(vm, 0)) == PX_EXCEPTION) goto out;
    if (lim == 0) goto done;
    if (sep == PX_UNDEFINED) {
        if (px_array_push(vm, A, S) < 0) goto out;
        goto done;
    }
    if (!(s = px_str_flat(vm, S)) || !(p = px_str_flat(vm, R))) goto out;
    if (p->len == 0) {
        for (i = 0; i < s->len && i < lim; i++) {
            v = px_str_slice(vm, S, i, i + 1);
            if (v == PX_EXCEPTION || px_array_push(vm, A, v) < 0) goto out;
            s = px_str_flat(vm, S);
        }
        goto done;
    }
    if (s->len == 0) {
        if (px_array_push(vm, A, S) < 0) goto out;
        goto done;
    }
    for (j = str_index_of(s, p, 0); j >= 0; j = str_index_of(s, p, i)) {
        v = px_str_slice(vm, S, i, (uint32_t)j);
        if (v == PX_EXCEPTION || px_array_push(vm, A, v) < 0) goto out;
        if (((PxArray *)px_ptr(A))->length == lim) goto done;
        s = px_str_flat(vm, S);
        p = px_str_flat(vm, R);
        i = (uint32_t)j + p->len;
    }
    v = px_str_slice(vm, S, i, s->len);
    if (v == PX_EXCEPTION || px_array_push(vm, A, v) < 0) goto out;
done:
    r = A;
out:
    vm->nroots = nr;
    return r;
}

/* String.prototype.match, matchAll, replace, replaceAll, search and split:
 * a pattern object with the protocol's symbol method handles the call;
 * otherwise a string pattern is compiled (match, matchAll, search) or
 * used as it is (replace, replaceAll, split). */
PxValue px_string_regexp_method(PxVM *vm, PxValue t, int argc, PxValue *argv, int which) {
    static const char *const names[] = {"match", "matchAll", "replace", "replaceAll", "search", "split"};
    PxValue  arg = ARG(0), S = PX_UNDEFINED, f = PX_UNDEFINED, r = PX_EXCEPTION, sym, args[2];
    uint32_t nr = vm->nroots;
    if (t == PX_UNDEFINED || t == PX_NULL)
        return px_throw_error(vm, PX_TYPE_ERROR, "String.prototype.%s called on null or undefined", names[which]);
    sym = which == PX_SM_MATCH       ? vm->sym_match
          : which == PX_SM_MATCH_ALL ? vm->sym_match_all
          : which == PX_SM_SEARCH    ? vm->sym_search
          : which == PX_SM_SPLIT     ? vm->sym_split
                                     : vm->sym_replace;
    PX_ROOT(vm, t);
    PX_ROOT(vm, arg);
    PX_ROOT(vm, S);
    PX_ROOT(vm, f);
    /* only objects are asked (ECMA-262 2025: a primitive's prototype is not) */
    if (px_is_obj(arg)) {
        if (which == PX_SM_MATCH_ALL || which == PX_SM_REPLACE_ALL) {
            int is = is_regexp(vm, arg);
            if (is < 0) goto out;
            if (is) {
                PxString *fs;
                uint32_t  k;
                if ((f = px_intern_cstr(vm, "flags")) == PX_EXCEPTION || (f = px_get(vm, arg, f)) == PX_EXCEPTION)
                    goto out;
                if (f == PX_UNDEFINED || f == PX_NULL) {
                    px_throw_error(vm, PX_TYPE_ERROR, "String.prototype.%s: the RegExp's flags are %s", names[which],
                                   f == PX_NULL ? "null" : "undefined");
                    goto out;
                }
                if ((f = px_to_string(vm, f)) == PX_EXCEPTION || !(fs = px_str_flat(vm, f))) goto out;
                for (k = 0; k < fs->len && px_str_at(fs, k) != 'g'; k++) {}
                if (k == fs->len) {
                    px_throw_error(vm, PX_TYPE_ERROR, "String.prototype.%s called with a non-global RegExp", names[which]);
                    goto out;
                }
            }
        }
        f = px_get(vm, arg, sym);
        if (f == PX_EXCEPTION) goto out;
        if (f != PX_UNDEFINED && f != PX_NULL) {
            args[0] = t;
            args[1] = ARG(1);
            r = px_call(vm, f, arg, which == PX_SM_REPLACE || which == PX_SM_REPLACE_ALL || which == PX_SM_SPLIT ? 2 : 1,
                        args);
            goto out;
        }
    }
    if ((S = px_to_string(vm, t)) == PX_EXCEPTION) goto out;
    switch (which) {
    case PX_SM_REPLACE:
    case PX_SM_REPLACE_ALL: r = string_replace(vm, S, arg, ARG(1), which == PX_SM_REPLACE_ALL); break;
    case PX_SM_SPLIT: r = string_split(vm, S, arg, ARG(1)); break;
    default:
        f = which == PX_SM_MATCH_ALL ? px_str_from_cstr(vm, "g") : PX_UNDEFINED;
        if (f == PX_EXCEPTION || (f = regexp_new(vm, arg, f)) == PX_EXCEPTION) break;
        r = px_get(vm, f, sym);
        if (r != PX_EXCEPTION) r = px_call(vm, r, f, 1, &S);
        break;
    }
out:
    vm->nroots = nr;
    return r;
}

/* ------------------------------------------------------------ setup */

/* A method: not a constructor, with the keys as its data. */
static PxValue make_fn(PxVM *vm, PxNativeFn fn, const char *name, int length, int magic, PxValue keys) {
    PxValue f = px_make_native(vm, fn, name, length, magic);
    if (f != PX_EXCEPTION) {
        ((PxNative *)px_ptr(f))->data = keys;
        ((PxObject *)px_ptr(f))->flags |= PX_OBJ_NOT_CTOR;
    }
    return f;
}

int px_regexp_init(PxVM *vm) {
    static const struct {
        const char *name;
        PxNativeFn  fn;
        int         length;
    } methods[] = {{"exec", rep_exec, 1},
                   {"test", rep_test, 1},
                   {"toString", rep_to_string, 0},
                   {"match", rep_match, 1},
                   {"matchAll", rep_match_all, 1},
                   {"replace", rep_replace, 2},
                   {"search", rep_search, 1},
                   {"split", rep_split, 2}};
    PxValue *syms[5] = {&vm->sym_match, &vm->sym_match_all, &vm->sym_replace, &vm->sym_search, &vm->sym_split};
    PxValue  proto = vm->protos[PX_PROTO_REGEXP], keys, f = PX_UNDEFINED, k = PX_UNDEFINED, ctor;
    uint32_t nr = vm->nroots;
    PxVec   *kv;
    PxObject *ip;
    char     buf[48];
    int      i;
    PX_ROOT(vm, f);
    PX_ROOT(vm, k);
    if (!(kv = px_vec_new(vm, K_COUNT))) goto fail;
    keys = px_from_ptr(kv);
    PX_ROOT(vm, keys);
#define SETKEY(i, s)                                                   \
    if ((k = px_intern_cstr(vm, s)) == PX_EXCEPTION) goto fail;        \
    ((PxVec *)px_ptr(keys))->items[i] = k
    SETKEY(K_FLAGS, "flags");
    SETKEY(K_EXEC, "exec");
    SETKEY(K_SOURCE, "source");
    for (i = 0; i < 7; i++) {
        SETKEY(K_FLAG0 + i, k_flag_names[i]);
    }
#undef SETKEY
    /* the protocol's well-known symbols */
    for (i = 0; i < 5; i++) {
        snprintf(buf, sizeof buf, "Symbol.%s", methods[3 + i].name);
        if ((k = px_str_from_cstr(vm, buf)) == PX_EXCEPTION || (*syms[i] = px_symbol_new(vm, k)) == PX_EXCEPTION ||
            px_def_value(vm, vm->ctors[PX_PROTO_SYMBOL], methods[3 + i].name, *syms[i], 0) < 0)
            goto fail;
    }
    /* %RegExpStringIteratorPrototype% */
    if (!(ip = px_obj_new(vm, PX_T_OBJECT, sizeof(PxObject), vm->protos[PX_PROTO_ITERATOR]))) goto fail;
    ((PxVec *)px_ptr(keys))->items[K_ITERPROTO] = px_from_ptr(ip);
    if (!(kv = px_vec_new(vm, 4 * RE_CACHE + 1))) goto fail;
    kv->items[4 * RE_CACHE]                 = px_from_smi(0);
    ((PxVec *)px_ptr(keys))->items[K_CACHE] = px_from_ptr(kv);
    if ((f = make_fn(vm, rsi_next, "next", 0, 0, keys)) == PX_EXCEPTION ||
        px_define(vm, px_from_ptr(ip), vm->atom[PX_ATOM_next], f, PX_ATTR_HIDDEN) < 0 ||
        (k = px_str_from_cstr(vm, "RegExp String Iterator")) == PX_EXCEPTION ||
        px_define(vm, px_from_ptr(ip), vm->sym_to_string_tag, k, PX_ATTR_CONFIGURABLE) < 0)
        goto fail;
    /* RegExp and RegExp.prototype */
    if ((ctor = px_make_native(vm, regexp_ctor, "RegExp", 2, 0)) == PX_EXCEPTION) goto fail;
    ((PxNative *)px_ptr(ctor))->data = keys;
    vm->ctors[PX_PROTO_REGEXP]       = ctor;
    if (px_def_value(vm, vm->global, "RegExp", ctor, PX_ATTR_HIDDEN) < 0 ||
        px_def_value(vm, ctor, "prototype", proto, 0) < 0 ||
        px_define(vm, proto, vm->atom[PX_ATOM_constructor], ctor, PX_ATTR_HIDDEN) < 0)
        goto fail;
    for (i = 0; i < PX_COUNTOF(methods); i++) {
        if (i < 3) {
            snprintf(buf, sizeof buf, "%s", methods[i].name);
            k = px_intern_cstr(vm, buf);
        } else {
            snprintf(buf, sizeof buf, "[Symbol.%s]", methods[i].name);
            k = *syms[i - 3];
        }
        if (k == PX_EXCEPTION || (f = make_fn(vm, methods[i].fn, buf, methods[i].length, 0, keys)) == PX_EXCEPTION ||
            px_define(vm, proto, k, f, PX_ATTR_HIDDEN) < 0)
            goto fail;
    }
    for (i = -2; i < 7; i++) {
        const char *name = i == -2 ? "flags" : i == -1 ? "source" : k_flag_names[i];
        snprintf(buf, sizeof buf, "get %s", name);
        if ((k = px_intern_cstr(vm, name)) == PX_EXCEPTION ||
            (f = make_fn(vm, i == -2 ? rep_flags : i == -1 ? rep_source : rep_flag, buf, 0,
                         i < 0 ? 0 : (int)k_flag_bits[i], keys)) == PX_EXCEPTION ||
            px_define_accessor(vm, proto, k, f, PX_UNDEFINED, PX_ATTR_CONFIGURABLE) < 0)
            goto fail;
    }
    if ((f = make_fn(vm, regexp_species, "get [Symbol.species]", 0, 0, keys)) == PX_EXCEPTION ||
        px_define_accessor(vm, ctor, vm->sym_species, f, PX_UNDEFINED, PX_ATTR_CONFIGURABLE) < 0)
        goto fail;
    vm->nroots = nr;
    return 0;
fail:
    vm->nroots = nr;
    return -1;
}
