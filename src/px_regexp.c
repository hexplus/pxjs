/* A backtrack entry: a = pc << 3 | kind. */
typedef struct Bt {
    int32_t a, b, c;
} Bt;
enum {
    BT_BRANCH, /* resume at pc, position b */
    BT_CAP,    /* capture slot (a >> 3) had value b */
    BT_REG,    /* register (a >> 3) had value b */
    BT_GREEDY, /* R_STAR at pc: give back one character of b (not past c) */
    BT_LAZY    /* R_STAR at pc: take one more character at b (c taken so far) */
};

typedef struct ReM {
    PxVM           *vm;
    const int32_t  *code;
    const uint8_t  *l1;  /* the input, Latin-1 ... */
    const uint16_t *u16; /* ... or UTF-16 */
    int32_t         len;
    int             u;
    int32_t        *caps;  /* 2 per group */
    int32_t        *regs;  /* loop registers, then each group's start */
    int32_t         nregs; /* loop registers */
    Bt             *st;
    uint32_t        sp, cap;
    uint32_t        steps, budget;
    int32_t         first_end; /* where a leading greedy loop stopped (see re_match) */
    int             error;     /* 1 too complex, 2 exception (interrupted) */
} ReM;

static inline uint32_t unit_at(const ReM *m, int32_t i) { return m->u16 ? m->u16[i] : m->l1[i]; }

static int push_bt(ReM *m, int32_t a, int32_t b, int32_t c) {
    if (m->sp == m->cap) {
        uint32_t ncap = m->cap ? m->cap * 2 : 64;
        Bt      *n    = ncap > RE_MAX_STACK ? NULL : (Bt *)realloc(m->st, ncap * sizeof(Bt));
        if (!n) {
            m->error = 1;
            return -1;
        }
        m->st  = n;
        m->cap = ncap;
    }
    m->st[m->sp].a = a;
    m->st[m->sp].b = b;
    m->st[m->sp].c = c;
    m->sp++;
    return 0;
}

static int set_cap(ReM *m, int32_t i, int32_t v) {
    if (push_bt(m, i << 3 | BT_CAP, m->caps[i], 0) < 0) return -1;
    m->caps[i] = v;
    return 0;
}

static int set_reg(ReM *m, int32_t i, int32_t v) {
    if (push_bt(m, i << 3 | BT_REG, m->regs[i], 0) < 0) return -1;
    m->regs[i] = v;
    return 0;
}

/* The character after *pos (or before it, backwards), moving *pos past
 * it; -1 at the end. In Unicode mode a surrogate pair is one character. */
static int32_t get_char(const ReM *m, int32_t *pos, int back) {
    int32_t  p = *pos;
    uint32_t c;
    if (!back) {
        if (p >= m->len) return -1;
        c = unit_at(m, p++);
        if (m->u && IS_HI(c) && p < m->len && IS_LO(unit_at(m, p)))
            c = 0x10000 + ((c - 0xD800) << 10) + (unit_at(m, p++) - 0xDC00);
    } else {
        if (p <= 0) return -1;
        c = unit_at(m, --p);
        if (m->u && IS_LO(c) && p > 0 && IS_HI(unit_at(m, p - 1)))
            c = 0x10000 + ((unit_at(m, --p) - 0xD800) << 10) + (c - 0xDC00);
    }
    *pos = p;
    return (int32_t)c;
}

/* One R_CHAR, R_ANY or R_CLASS at *pos. */
static int match1(const ReM *m, const int32_t *op, int32_t *pos) {
    int32_t  p  = *pos, ch = get_char(m, &p, op[0] & R_BACK);
    uint32_t cc;
    if (ch < 0) return 0;
    cc = op[0] & R_FLAG && R_OP(op[0]) != R_ANY ? canon((uint32_t)ch, m->u) : (uint32_t)ch;
    switch (R_OP(op[0])) {
    case R_CHAR:
        if (cc != (uint32_t)op[1]) return 0;
        break;
    case R_ANY:
        if (!(op[0] & R_FLAG) && is_line_term((uint32_t)ch)) return 0;
        break;
    default:
        if (ranges_have((const uint32_t *)op + 3, op[2], cc) == op[1]) return 0;
        break;
    }
    *pos = p;
    return 1;
}

static int op_len(const int32_t *op) { return R_OP(op[0]) == R_ANY ? 1 : R_OP(op[0]) == R_CHAR ? 2 : 3 + 2 * op[2]; }

static int is_word_at(const ReM *m, int32_t i, int extra) {
    uint32_t c;
    if (i < 0 || i >= m->len) return 0;
    c = unit_at(m, i);
    return is_word_ascii(c) || (extra && is_extra_word(c));
}

/* A backreference to group g at *pos. */
static int match_ref(const ReM *m, int g, int back, int icase, int32_t *pos) {
    int32_t a = m->caps[2 * g], b = m->caps[2 * g + 1], n = b - a, start, k;
    if (a < 0 || b < 0) return 1; /* an undefined group matches the empty string */
    start = back ? *pos - n : *pos;
    if (start < 0 || start + n > m->len) return 0;
    if (!icase) {
        for (k = 0; k < n; k++)
            if (unit_at(m, a + k) != unit_at(m, start + k)) return 0;
    } else {
        /* case pairs never cross planes, so both sides have the same length */
        int32_t x = a, y = start;
        while (x < b) {
            int32_t cx = get_char(m, &x, 0), cy = get_char(m, &y, 0);
            if (cy < 0 || canon((uint32_t)cx, m->u) != canon((uint32_t)cy, m->u)) return 0;
        }
    }
    *pos = back ? start : start + n;
    return 1;
}

/* Runs the program from pc at pos. Returns 1 (a match), 0, or -1
 * (m->error). A lookaround runs its body in a nested call: the nesting is
 * the pattern's, bounded by RE_MAX_DEPTH. */
static int re_run(ReM *m, int32_t pc, int32_t pos) {
    const int32_t *code = m->code;
    uint32_t       base = m->sp;
    for (;;) {
        int32_t op = code[pc];
        if (++m->steps > m->budget) {
            m->error = 1;
            return -1;
        }
        if (!(m->steps & 0xFFFF) && px_check_interrupt(m->vm) < 0) {
            m->error = 2;
            return -1;
        }
        switch (R_OP(op)) {
        case R_CHAR:
        case R_ANY:
        case R_CLASS:
            if (!match1(m, code + pc, &pos)) goto fail;
            pc += op_len(code + pc);
            continue;
        case R_SPLIT:
            if (push_bt(m, (pc + code[pc + 2]) << 3 | BT_BRANCH, pos, 0) < 0) return -1;
            pc += code[pc + 1];
            continue;
        case R_JMP: pc += code[pc + 1]; continue;
        case R_OPEN:
            if (set_reg(m, m->nregs + code[pc + 1], pos) < 0) return -1;
            pc += 2;
            continue;
        case R_CLOSE: {
            int32_t g = code[pc + 1], o = m->regs[m->nregs + g];
            if (set_cap(m, 2 * g, op & R_BACK ? pos : o) < 0 || set_cap(m, 2 * g + 1, op & R_BACK ? o : pos) < 0)
                return -1;
            pc += 2;
            continue;
        }
        case R_RESET: {
            int32_t g;
            for (g = code[pc + 1]; g < code[pc + 2]; g++)
                if (m->caps[2 * g] >= 0 && (set_cap(m, 2 * g, -1) < 0 || set_cap(m, 2 * g + 1, -1) < 0)) return -1;
            pc += 3;
            continue;
        }
        case R_BOL:
            if (pos != 0 && !(op & R_FLAG && is_line_term(unit_at(m, pos - 1)))) goto fail;
            pc++;
            continue;
        case R_EOL:
            if (pos != m->len && !(op & R_FLAG && is_line_term(unit_at(m, pos)))) goto fail;
            pc++;
            continue;
        case R_WORDB:
        case R_NWORDB:
            if ((is_word_at(m, pos - 1, op & R_FLAG) != is_word_at(m, pos, op & R_FLAG)) != (R_OP(op) == R_WORDB))
                goto fail;
            pc++;
            continue;
        case R_BACKREF:
            if (!match_ref(m, code[pc + 1], op & R_BACK, op & R_FLAG, &pos)) goto fail;
            pc += 2;
            continue;
        case R_LOOK: {
            int      neg  = code[pc + 1], r;
            uint32_t mark = m->sp, k, w;
            r             = re_run(m, pc + 3, pos);
            if (r < 0) return -1;
            /* the body's own choices do not survive it; its captures do
             * (positive) or are undone (negative) */
            if (neg && r) {
                while (m->sp > mark) {
                    Bt *b = &m->st[--m->sp];
                    if ((b->a & 7) == BT_CAP) m->caps[b->a >> 3] = b->b;
                    else if ((b->a & 7) == BT_REG) m->regs[b->a >> 3] = b->b;
                }
            } else {
                for (k = w = mark; k < m->sp; k++)
                    if ((m->st[k].a & 7) == BT_CAP || (m->st[k].a & 7) == BT_REG) m->st[w++] = m->st[k];
                m->sp = w;
            }
            if (r == neg) goto fail;
            pc += code[pc + 2];
            continue;
        }
        case R_LOOKEND: return 1;
        case R_REPINIT:
            if (set_reg(m, code[pc + 1], 0) < 0) return -1;
            pc += 2;
            continue;
        case R_REP: {
            int32_t n = m->regs[code[pc + 1]];
            if (n < code[pc + 2]) {
                pc += 6;
            } else if (code[pc + 3] != RE_INF && n >= code[pc + 3]) {
                pc += code[pc + 5];
            } else if (code[pc + 4]) {
                if (push_bt(m, (pc + code[pc + 5]) << 3 | BT_BRANCH, pos, 0) < 0) return -1;
                pc += 6;
            } else {
                if (push_bt(m, (pc + 6) << 3 | BT_BRANCH, pos, 0) < 0) return -1;
                pc += code[pc + 5];
            }
            continue;
        }
        case R_SETPOS:
            if (set_reg(m, code[pc + 1], pos) < 0) return -1;
            pc += 2;
            continue;
        case R_REPEND: {
            int32_t r = code[pc + 1];
            if (m->regs[r] >= code[pc + 2] && pos == m->regs[r + 1]) goto fail; /* an empty iteration */
            if (set_reg(m, r, m->regs[r] + 1) < 0) return -1;
            pc += code[pc + 3];
            continue;
        }
        case R_STAR: {
            int32_t min = code[pc + 1], max = code[pc + 2], n = 0, limit = pos;
            if (code[pc + 3]) {
                while (n < max && match1(m, code + pc + 4, &pos)) {
                    if (++n == min) limit = pos;
                    m->steps++;
                }
                if (pc == 2) m->first_end = pos;
                if (n < min) goto fail;
                if (n > min && push_bt(m, pc << 3 | BT_GREEDY, pos, limit) < 0)
                    return -1;
            } else {
                while (n < min && match1(m, code + pc + 4, &pos)) {
                    n++;
                    m->steps++;
                }
                if (n < min) goto fail;
                if (n < max && push_bt(m, pc << 3 | BT_LAZY, pos, n) < 0) return -1;
            }
            pc += 4 + op_len(code + pc + 4);
            continue;
        }
        case R_MATCH: m->caps[1] = pos; return 1;
        default: m->error = 1; return -1;
        }
    fail:
        for (;;) {
            Bt *b;
            if (m->sp == base) return 0;
            b = &m->st[--m->sp];
            switch (b->a & 7) {
            case BT_CAP: m->caps[b->a >> 3] = b->b; continue;
            case BT_REG: m->regs[b->a >> 3] = b->b; continue;
            case BT_BRANCH:
                pc  = b->a >> 3;
                pos = b->b;
                break;
            case BT_GREEDY: {
                /* give back one character (a surrogate pair is one in Unicode mode) */
                int32_t p = b->b, limit = b->c;
                pc = b->a >> 3;
                if (!(code[pc + 4] & R_BACK)) {
                    p--;
                    if (m->u && p > limit && IS_LO(unit_at(m, p)) && IS_HI(unit_at(m, p - 1))) p--;
                } else if (m->u && p + 1 < limit && IS_HI(unit_at(m, p)) && IS_LO(unit_at(m, p + 1))) {
                    p += 2;
                } else {
                    p++;
                }
                if (p != limit) {
                    b->b = p;
                    m->sp++;
                }
                pos = p;
                pc += 4 + op_len(code + pc + 4);
                break;
            }
            default: { /* BT_LAZY */
                int32_t p = b->b;
                pc = b->a >> 3;
                if (!match1(m, code + pc + 4, &p)) continue;
                if (++b->c < code[pc + 2]) {
                    b->b = p;
                    m->sp++;
                }
                pos = p;
                pc += 4 + op_len(code + pc + 4);
                break;
            }
            }
            break;
        }
    }
}

/* Matches at `start` or, unless sticky, at the first position after it
 * where the pattern matches. Returns 1 (caps filled; caps[0] is start's
 * position even when, in Unicode mode, it splits a surrogate pair and the
 * match began at the pair), 0, or -1 (an exception was thrown). */
static int re_match(PxVM *vm, PxRegExp *re, PxString *s, uint32_t start, int sticky, int32_t *caps) {
    const int32_t *prog = (const int32_t *)(const void *)re->prog->data;
    ReM            m;
    int32_t        local[32];
    uint32_t       pos = start, nr = (uint32_t)prog[0] + re->ngroups;
    int            r = 0;
    /* Two ways to try fewer starts. A pattern that begins with a literal
     * code unit can only match where that unit is. And when a leading
     * greedy unbounded loop fails from a start after consuming up to
     * first_end, it has tried every continuation from there down: starting
     * anywhere up to first_end would repeat that work (no captures, and
     * nothing after it knows where the match began). This keeps searches
     * like /x*y/ over long runs of x linear. */
    int     skip = R_OP(prog[2]) == R_STAR && prog[4] == RE_INF && prog[5] && !(prog[6] & R_BACK);
    int32_t lead = prog[2] == R_CHAR && prog[3] <= 0xFFFF &&
                           !IS_HI(prog[3]) && !IS_LO(prog[3])
                       ? prog[3]
                       : -1;
    memset(&m, 0, sizeof m);
    m.vm        = vm;
    m.code      = prog;
    m.len       = (int32_t)s->len;
    m.u16       = s->wide ? px_str_u16(s) : NULL;
    m.l1        = px_str_l1(s);
    m.u         = (re->flags & PX_RE_UNICODE) != 0;
    m.caps      = caps;
    m.nregs     = prog[0];
    m.regs      = nr <= 32 ? local : (int32_t *)calloc(nr, sizeof(int32_t));
    m.budget    = s->len > (0x7FFFFFFFu - RE_STEPS_BASE) / RE_STEPS_PER_UNIT ? 0x7FFFFFFFu
                                                                             : RE_STEPS_BASE + s->len * RE_STEPS_PER_UNIT;
    if (!m.regs) {
        px_throw_oom(vm);
        return -1;
    }
    for (;;) {
        int32_t  p = (int32_t)pos;
        uint32_t g;
        if (lead >= 0 && !sticky) {
            while (pos < s->len && unit_at(&m, (int32_t)pos) != (uint32_t)lead) pos++;
            if (pos >= s->len) break;
            p = (int32_t)pos;
        }
        /* in Unicode mode, a position inside a surrogate pair means the pair */
        if (m.u && p > 0 && p < m.len && IS_LO(unit_at(&m, p)) && IS_HI(unit_at(&m, p - 1))) p--;
        for (g = 0; g < 2 * re->ngroups; g++) caps[g] = -1;
        m.sp        = 0;
        m.first_end = -1;
        r           = re_run(&m, 2, p);
        if (r != 0 || sticky || pos >= s->len) break;
        if (skip && m.first_end > (int32_t)pos) pos = (uint32_t)m.first_end;
        if (pos >= s->len) break;
        pos += m.u && IS_HI(unit_at(&m, (int32_t)pos)) && pos + 1 < s->len && IS_LO(unit_at(&m, (int32_t)pos + 1)) ? 2 : 1;
    }
    if (r > 0) caps[0] = (int32_t)pos;
    free(m.st);
    if (m.regs != local) free(m.regs);
    if (r < 0 && m.error == 1) px_throw_error(vm, PX_RANGE_ERROR, "regular expression too complex for this input");
    return r;
}

