static int to_length(PxVM *vm, PxValue v, PxIdx *out) {
    double d;
    if (px_is_smi(v)) {
        *out = px_smi(v) < 0 ? 0 : px_smi(v);
        return 0;
    }
    if (px_to_number(vm, v, &d) < 0) return -1;
    *out = isnan(d) || d <= 0 ? 0 : d >= (double)RE_MAX_INDEX ? RE_MAX_INDEX : (PxIdx)d;
    return 0;
}

static int get_last_index(PxVM *vm, PxValue R, PxIdx *out) {
    PxValue v = px_get(vm, R, vm->atom[PX_ATOM_lastIndex]);
    return v == PX_EXCEPTION ? -1 : to_length(vm, v, out);
}

static int set_last_index(PxVM *vm, PxValue R, PxIdx i) {
    PxValue n = px_idx_value(vm, i);
    int     r;
    if (n == PX_EXCEPTION) return -1;
    PX_ROOT(vm, n);
    r = px_set(vm, R, vm->atom[PX_ATOM_lastIndex], n);
    px_pop_roots(vm, 1);
    return r;
}

/* AdvanceStringIndex */
static PxIdx advance(PxVM *vm, PxValue S, PxIdx i, int unicode) {
    PxString *s = px_str_flat(vm, S); /* S is flat already: no allocation */
    if (!unicode || i + 1 >= (PxIdx)s->len) return i + 1;
    return IS_HI(px_str_at(s, (uint32_t)i)) && IS_LO(px_str_at(s, (uint32_t)i + 1)) ? i + 2 : i + 1;
}

/* IsRegExp: -1 exception, else 0 / 1 */
static int is_regexp(PxVM *vm, PxValue v) {
    PxValue m;
    if (!px_is_obj(v)) return 0;
    m = px_get(vm, v, vm->sym_match);
    if (m == PX_EXCEPTION) return -1;
    if (m != PX_UNDEFINED) return px_truthy(m);
    return as_re(v) != NULL;
}

/* SpeciesConstructor(o, %RegExp%) */
static PxValue species_ctor(PxVM *vm, PxValue o) {
    PxValue c = px_get(vm, o, vm->atom[PX_ATOM_constructor]), s;
    if (c == PX_EXCEPTION) return c;
    if (c == PX_UNDEFINED) return vm->ctors[PX_PROTO_REGEXP];
    if (!px_is_obj(c)) return px_throw_error(vm, PX_TYPE_ERROR, "the constructor property is not an object");
    PX_ROOT(vm, c);
    s = px_get(vm, c, vm->sym_species);
    px_pop_roots(vm, 1);
    if (s == PX_EXCEPTION) return s;
    if (s == PX_UNDEFINED || s == PX_NULL) return vm->ctors[PX_PROTO_REGEXP];
    if (!px_is_constructor(s)) return px_throw_error(vm, PX_TYPE_ERROR, "[Symbol.species] is not a constructor");
    return s;
}

static int parse_flags(PxString *f, uint32_t *out) {
    uint32_t k, bits = 0;
    for (k = 0; k < f->len; k++) {
        uint16_t    ch = px_str_at(f, k);
        const char *at = ch && ch < 128 ? strchr(k_flag_chars, ch) : NULL;
        if (!at || (bits & k_flag_bits[at - k_flag_chars])) return -1;
        bits |= k_flag_bits[at - k_flag_chars];
    }
    *out = bits;
    return 0;
}

static PxValue flags_string(PxVM *vm, uint32_t bits) {
    char buf[8];
    int  n = 0, k;
    for (k = 0; k < 7; k++)
        if (bits & k_flag_bits[k]) buf[n++] = k_flag_chars[k];
    return px_str_from_utf8(vm, buf, (size_t)n);
}

/* Compiles a flat pattern: NULL or the error message. */
static const char *compile_str(ReC *c, PxString *ps, uint32_t flags) {
    uint16_t   *units = (uint16_t *)malloc((ps->len ? ps->len : 1) * sizeof(uint16_t));
    uint32_t    k;
    const char *err;
    memset(c, 0, sizeof *c);
    if (!units) return "out of memory";
    for (k = 0; k < ps->len; k++) units[k] = px_str_at(ps, k);
    err = re_compile(c, units, ps->len, flags);
    free(units);
    return err;
}

/* Recently compiled patterns, whose programs the RegExps built from them
 * share (a program never changes): a literal in a loop compiles once.
 * RE_CACHE entries [pattern, flags, program, names], then the next entry
 * to replace, in a vector kept in the RegExp constructor's data. */
#define RE_CACHE 16

static PxValue *cache_slots(PxVM *vm) {
    PxValue ctor = vm->ctors[PX_PROTO_REGEXP];
    return px_is_obj(ctor) ? ((PxVec *)px_ptr(((PxVec *)px_ptr(((PxNative *)px_ptr(ctor))->data))->items[K_CACHE]))->items
                           : NULL;
}

/* RegExpCreate / RegExpInitialize: a new RegExp from a pattern and flags
 * (undefined, or anything ToString accepts). */
static PxValue regexp_new(PxVM *vm, PxValue P, PxValue F) {
    uint32_t    nr = vm->nroots, flags = 0;
    PxValue     names = PX_UNDEFINED, prog = PX_UNDEFINED, rv = PX_UNDEFINED;
    PxString   *ps, *fs;
    PxRegExp   *re;
    const char *err;
    ReC         c;
    int         g;
    PxValue    *slots;
    PX_ROOT(vm, P);
    PX_ROOT(vm, F);
    PX_ROOT(vm, names);
    PX_ROOT(vm, prog);
    PX_ROOT(vm, rv);
    P = P == PX_UNDEFINED ? vm->atom[PX_ATOM_empty] : px_to_string(vm, P);
    if (P == PX_EXCEPTION) goto fail;
    F = F == PX_UNDEFINED ? vm->atom[PX_ATOM_empty] : px_to_string(vm, F);
    if (F == PX_EXCEPTION || !(fs = px_str_flat(vm, F)) || !(ps = px_str_flat(vm, P))) goto fail;
    if (parse_flags(fs, &flags) < 0) {
        px_throw_error(vm, PX_SYNTAX_ERROR, "invalid regular expression flags");
        goto fail;
    }
    if ((slots = cache_slots(vm)) != NULL)
        for (g = 0; g < RE_CACHE; g++)
            if (slots[4 * g + 1] == px_from_smi((int32_t)flags) &&
                (slots[4 * g] == P || (px_str_len(slots[4 * g]) == ps->len && px_str_eq(vm, slots[4 * g], P) == 1))) {
                prog  = slots[4 * g + 2];
                names = slots[4 * g + 3];
                goto make;
            }
    err = compile_str(&c, ps, flags);
    if (err) {
        char src[80];
        rec_free(&c);
        px_str_to_utf8(vm, P, src, sizeof src);
        px_throw_error(vm, PX_SYNTAX_ERROR, "invalid regular expression /%s/: %s", src, err);
        goto fail;
    }
    if (c.has_names) {
        PxVec *nv = px_vec_new(vm, (uint32_t)c.total + 1);
        if (!nv) goto fail_c;
        names = px_from_ptr(nv);
        for (g = 1; g <= c.total; g++) {
            PxValue n;
            if (!c.names[g]) continue;
            n = px_str_new_u16(vm, c.names[g], c.name_len[g]);
            if (n == PX_EXCEPTION || (n = px_intern(vm, n)) == PX_EXCEPTION) goto fail_c;
            ((PxVec *)px_ptr(names))->items[g] = n;
        }
    }
    {
        PxBytes *pb = px_bytes_new(vm, c.code, c.len * (uint32_t)sizeof(int32_t));
        if (!pb) goto fail_c;
        prog = px_from_ptr(pb);
    }
    rec_free(&c);
    if ((slots = cache_slots(vm)) != NULL) {
        g                   = px_smi(slots[4 * RE_CACHE]);
        slots[4 * g]        = P;
        slots[4 * g + 1]    = px_from_smi((int32_t)flags);
        slots[4 * g + 2]    = prog;
        slots[4 * g + 3]    = names;
        slots[4 * RE_CACHE] = px_from_smi((g + 1) % RE_CACHE);
    }
make:
    re = (PxRegExp *)px_obj_new(vm, PX_T_REGEXP, sizeof(PxRegExp), vm->protos[PX_PROTO_REGEXP]);
    if (!re) goto fail;
    re->prog    = (PxBytes *)px_ptr(prog);
    re->source  = P;
    re->flags   = flags;
    re->ngroups = ((const int32_t *)(const void *)re->prog->data)[1];
    re->names   = names;
    rv          = px_from_ptr(re);
    if (px_define(vm, rv, vm->atom[PX_ATOM_lastIndex], px_from_smi(0), PX_ATTR_WRITABLE) < 0) goto fail;
    vm->nroots = nr;
    return rv;
fail_c:
    rec_free(&c);
fail:
    vm->nroots = nr;
    return PX_EXCEPTION;
}

PxValue px_regexp_create(PxVM *vm, PxValue pattern, PxValue flags) { return regexp_new(vm, pattern, flags); }

static PxValue regexp_ctor(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    PxValue  pattern = ARG(0), flags = ARG(1), P = PX_UNDEFINED, F = PX_UNDEFINED, r = PX_EXCEPTION;
    uint32_t nr = vm->nroots;
    int      is;
    (void)t;
    PX_ROOT(vm, pattern);
    PX_ROOT(vm, flags);
    PX_ROOT(vm, P);
    PX_ROOT(vm, F);
    is = is_regexp(vm, pattern);
    if (is < 0) goto out;
    if (vm->native_new_target == PX_UNDEFINED && is && flags == PX_UNDEFINED) {
        PxValue c = px_get(vm, pattern, vm->atom[PX_ATOM_constructor]);
        if (c == PX_EXCEPTION) goto out;
        if (c == vm->ctors[PX_PROTO_REGEXP]) {
            r = pattern;
            goto out;
        }
    }
    if (as_re(pattern)) {
        P = as_re(pattern)->source;
        F = flags == PX_UNDEFINED ? flags_string(vm, as_re(pattern)->flags) : flags;
    } else if (is) {
        P = px_get(vm, pattern, KEY(K_SOURCE));
        if (P == PX_EXCEPTION) goto out;
        F = flags == PX_UNDEFINED ? px_get(vm, pattern, KEY(K_FLAGS)) : flags;
    } else {
        P = pattern;
        F = flags;
    }
    if (F != PX_EXCEPTION) r = regexp_new(vm, P, F);
out:
    vm->nroots = nr;
    return r;
}

/* RegExpBuiltinExec up to the match (22.2.7.2): reads and updates
 * lastIndex as the spec does. 1 (caps filled), 0, -1. */
static int builtin_exec(PxVM *vm, PxValue R, PxValue S, int32_t *caps) {
    PxRegExp *re;
    PxString *s;
    PxIdx     last;
    int       r, gy;
    if (get_last_index(vm, R, &last) < 0) return -1;
    re = as_re(R);
    gy = (re->flags & (PX_RE_GLOBAL | PX_RE_STICKY)) != 0;
    if (!gy) last = 0;
    s = px_str_flat(vm, S);
    if (!s) return -1;
    r = last > (PxIdx)s->len ? 0 : re_match(vm, re, s, (uint32_t)last, (re->flags & PX_RE_STICKY) != 0, caps);
    if (r < 0) return -1;
    if (gy && set_last_index(vm, R, r ? caps[1] : 0) < 0) return -1;
    return r;
}

/* RegExpExec (22.2.7.1): -1, 0 (null), 1 (a match). A RegExp whose exec
 * is the built-in one matches natively: captures in caps (2 per group),
 * *res undefined. Otherwise *res is the object exec returned. */
static int regexp_exec(PxVM *vm, PxValue R, PxValue S, int32_t *caps, PxValue *res) {
    PxValue exec = px_get(vm, R, KEY(K_EXEC)), r;
    *res         = PX_UNDEFINED;
    if (exec == PX_EXCEPTION) return -1;
    if (px_is_callable(exec) && !(is_builtin_exec(exec) && as_re(R))) {
        r = px_call(vm, exec, R, 1, &S);
        if (r == PX_EXCEPTION) return -1;
        if (r == PX_NULL) return 0;
        if (!px_is_obj(r)) {
            px_throw_error(vm, PX_TYPE_ERROR, "exec must return an object or null");
            return -1;
        }
        *res = r;
        return 1;
    }
    if (!as_re(R)) {
        px_throw_error(vm, PX_TYPE_ERROR, "RegExp exec called on an incompatible receiver");
        return -1;
    }
    return builtin_exec(vm, R, S, caps);
}

/* Room for R's captures: local if it fits, else malloc'd (NULL: OOM thrown). */
static int32_t *caps_for(PxVM *vm, PxValue R, int32_t *local, uint32_t nlocal) {
    uint32_t n = as_re(R) ? 2 * as_re(R)->ngroups : 2;
    int32_t *p = n <= nlocal ? local : (int32_t *)malloc(n * sizeof(int32_t));
    if (!p) px_throw_oom(vm);
    return p;
}
#define CAPS_FREE(p, local) \
    if ((p) != (local)) free(p)

static PxValue cap_value(PxVM *vm, PxValue S, const int32_t *caps, uint32_t g) {
    int32_t a = caps[2 * g], b = caps[2 * g + 1];
    if (a < 0 || b < 0) return PX_UNDEFINED;
    return px_str_slice(vm, S, (uint32_t)a, (uint32_t)(b > a ? b : a));
}

/* The groups object (null prototype) of a match, from its captures (an
 * array, element g for group g), or undefined without named groups. */
static PxValue groups_object(PxVM *vm, PxValue R, PxValue arr) {
    PxRegExp *re = as_re(R);
    PxValue   go;
    uint32_t  g;
    PxObject *o;
    if (re->names == PX_UNDEFINED) return PX_UNDEFINED;
    o = px_obj_new(vm, PX_T_OBJECT, sizeof(PxObject), PX_NULL);
    if (!o) return PX_EXCEPTION;
    go = px_from_ptr(o);
    PX_ROOT(vm, go);
    for (g = 1; g < as_re(R)->ngroups; g++) {
        PxValue k = ((PxVec *)px_ptr(as_re(R)->names))->items[g], v;
        if (k == PX_UNDEFINED) continue;
        v = px_get_index(vm, arr, g);
        if (v == PX_EXCEPTION || px_define(vm, go, k, v, PX_ATTR_DEFAULT) < 0) {
            go = PX_EXCEPTION;
            break;
        }
    }
    px_pop_roots(vm, 1);
    return go;
}

static PxValue index_pair(PxVM *vm, const int32_t *caps, uint32_t g) {
    PxValue a;
    if (caps[2 * g] < 0 || caps[2 * g + 1] < 0) return PX_UNDEFINED;
    a = px_array_new(vm, 2);
    if (a == PX_EXCEPTION) return a;
    /* SMIs: nothing to root */
    if (px_array_push(vm, a, px_from_smi(caps[2 * g])) < 0 ||
        px_array_push(vm, a, px_from_smi(caps[2 * g + 1] > caps[2 * g] ? caps[2 * g + 1] : caps[2 * g])) < 0)
        return PX_EXCEPTION;
    return a;
}

/* The array exec returns for a native match (22.2.7.2 steps 22-36). */
static PxValue make_result(PxVM *vm, PxValue R, PxValue S, const int32_t *caps) {
    uint32_t nr = vm->nroots, g, n = as_re(R)->ngroups;
    PxValue  A, v = PX_UNDEFINED, groups = PX_UNDEFINED, ind = PX_UNDEFINED;
    PX_ROOT(vm, R);
    PX_ROOT(vm, S);
    PX_ROOT(vm, v);
    PX_ROOT(vm, groups);
    PX_ROOT(vm, ind);
    A = px_array_new(vm, n);
    if (A == PX_EXCEPTION) goto fail;
    PX_ROOT(vm, A);
    for (g = 0; g < n; g++) {
        v = cap_value(vm, S, caps, g);
        if (v == PX_EXCEPTION || px_array_push(vm, A, v) < 0) goto fail;
    }
    groups = groups_object(vm, R, A);
    if (groups == PX_EXCEPTION || px_define(vm, A, vm->atom[PX_ATOM_index], px_from_smi(caps[0]), PX_ATTR_DEFAULT) < 0 ||
        px_define(vm, A, vm->atom[PX_ATOM_input], S, PX_ATTR_DEFAULT) < 0 ||
        px_define(vm, A, vm->atom[PX_ATOM_groups], groups, PX_ATTR_DEFAULT) < 0)
        goto fail;
    if (as_re(R)->flags & PX_RE_HASINDICES) {
        PxValue k = px_intern_cstr(vm, "indices");
        if (k == PX_EXCEPTION) goto fail;
        PX_ROOT(vm, k);
        ind = px_array_new(vm, n);
        if (ind == PX_EXCEPTION) goto fail;
        for (g = 0; g < n; g++) {
            v = index_pair(vm, caps, g);
            if (v == PX_EXCEPTION || px_array_push(vm, ind, v) < 0) goto fail;
        }
        groups = groups_object(vm, R, ind);
        if (groups == PX_EXCEPTION || px_define(vm, ind, vm->atom[PX_ATOM_groups], groups, PX_ATTR_DEFAULT) < 0 ||
            px_define(vm, A, k, ind, PX_ATTR_DEFAULT) < 0)
            goto fail;
    }
    vm->nroots = nr;
    return A;
fail:
    vm->nroots = nr;
    return PX_EXCEPTION;
}

static PxValue rep_exec(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    PxValue  S, r;
    int32_t  local[16], *caps;
    int      m;
    uint32_t nr = vm->nroots;
    if (!as_re(t)) return px_throw_error(vm, PX_TYPE_ERROR, "RegExp.prototype.exec called on an incompatible receiver");
    PX_ROOT(vm, t);
    S = px_to_string(vm, ARG(0));
    if (S == PX_EXCEPTION || !(caps = caps_for(vm, t, local, 16))) {
        vm->nroots = nr;
        return PX_EXCEPTION;
    }
    PX_ROOT(vm, S);
    m = builtin_exec(vm, t, S, caps);
    r = m < 0 ? PX_EXCEPTION : m == 0 ? PX_NULL : make_result(vm, t, S, caps);
    CAPS_FREE(caps, local);
    vm->nroots = nr;
    return r;
}

/* get flags (22.2.6.4) */
static PxValue rep_flags(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    char buf[8];
    int  n = 0, k;
    (void)argc;
    (void)argv;
    if (!px_is_obj(t)) return not_object(vm, "flags");
    PX_ROOT(vm, t);
    for (k = 0; k < 7; k++) {
        PxValue v = px_get(vm, t, KEY(K_FLAG0 + k));
        if (v == PX_EXCEPTION) {
            px_pop_roots(vm, 1);
            return v;
        }
        if (px_truthy(v)) buf[n++] = k_flag_chars[k];
    }
    px_pop_roots(vm, 1);
    return px_str_from_utf8(vm, buf, (size_t)n);
}

/* get global, ignoreCase, ...: magic is the flag's bit */
static PxValue rep_flag(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    (void)argc;
    (void)argv;
    if (as_re(t)) return px_bool((as_re(t)->flags & (uint32_t)vm->native_magic) != 0);
    if (t == vm->protos[PX_PROTO_REGEXP]) return PX_UNDEFINED;
    return px_throw_error(vm, PX_TYPE_ERROR, "RegExp flag getter called on an incompatible receiver");
}

/* get source: EscapeRegExpPattern -- '/' outside classes and line
 * terminators are escaped, so the source reads back as a literal. */
static PxValue rep_source(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    PxString *s;
    uint16_t *d;
    uint32_t  k, n = 0;
    int       in_class = 0, esc = 0;
    PxValue   r;
    (void)argc;
    (void)argv;
    if (!as_re(t)) {
        if (t == vm->protos[PX_PROTO_REGEXP]) return px_str_from_cstr(vm, "(?:)");
        return px_throw_error(vm, PX_TYPE_ERROR, "RegExp.prototype.source getter called on an incompatible receiver");
    }
    s = px_str_flat(vm, as_re(t)->source);
    if (!s) return PX_EXCEPTION;
    if (s->len == 0) return px_str_from_cstr(vm, "(?:)");
    d = (uint16_t *)malloc((size_t)s->len * 6 * sizeof(uint16_t));
    if (!d) return px_throw_oom(vm);
    for (k = 0; k < s->len; k++) {
        uint16_t    ch  = px_str_at(s, k);
        const char *rep = ch == '\n' ? "n" : ch == '\r' ? "r" : ch == 0x2028 ? "u2028" : ch == 0x2029 ? "u2029" : NULL;
        if (rep) {
            if (!esc) d[n++] = '\\';
            while (*rep) d[n++] = (uint16_t)*rep++;
            esc = 0;
            continue;
        }
        if (!esc && ch == '/' && !in_class) d[n++] = '\\';
        else if (!esc && ch == '[') in_class = 1;
        else if (!esc && ch == ']') in_class = 0;
        esc = !esc && ch == '\\';
        d[n++] = ch;
    }
    r = px_str_new_u16(vm, d, n);
    free(d);
    return r;
}

static PxValue rep_to_string(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    PxValue  src, fl = PX_UNDEFINED, r = PX_EXCEPTION;
    uint32_t nr = vm->nroots;
    (void)argc;
    (void)argv;
    if (!px_is_obj(t)) return not_object(vm, "toString");
    PX_ROOT(vm, t);
    PX_ROOT(vm, fl);
    src = px_get(vm, t, KEY(K_SOURCE));
    if (src == PX_EXCEPTION || (src = px_to_string(vm, src)) == PX_EXCEPTION) goto out;
    PX_ROOT(vm, src);
    fl = px_get(vm, t, KEY(K_FLAGS));
    if (fl == PX_EXCEPTION || (fl = px_to_string(vm, fl)) == PX_EXCEPTION) goto out;
    {
        PxValue slash = px_str_from_cstr(vm, "/");
        if (slash == PX_EXCEPTION) goto out;
        PX_ROOT(vm, slash);
        r = px_str_concat(vm, slash, src);
        if (r != PX_EXCEPTION) {
            PX_ROOT(vm, r);
            r = px_str_concat(vm, r, slash);
            if (r != PX_EXCEPTION) r = px_str_concat(vm, r, fl);
        }
    }
out:
    vm->nroots = nr;
    return r;
}

static PxValue rep_test(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    PxValue  S, res = PX_UNDEFINED;
    int32_t  local[16], *caps;
    int      m;
    uint32_t nr = vm->nroots;
    if (!px_is_obj(t)) return not_object(vm, "test");
    PX_ROOT(vm, t);
    PX_ROOT(vm, res);
    S = px_to_string(vm, ARG(0));
    if (S == PX_EXCEPTION || !(caps = caps_for(vm, t, local, 16))) {
        vm->nroots = nr;
        return PX_EXCEPTION;
    }
    PX_ROOT(vm, S);
    m = regexp_exec(vm, t, S, caps, &res);
    CAPS_FREE(caps, local);
    vm->nroots = nr;
    return m < 0 ? PX_EXCEPTION : px_bool(m);
}

/* ToString(Get(R, "flags")): the string, and its g/u/y as bits. */
static PxValue get_flags(PxVM *vm, PxValue R, uint32_t *bits) {
    PxValue   f = px_get(vm, R, KEY(K_FLAGS));
    PxString *s;
    uint32_t  k;
    if (f == PX_EXCEPTION || (f = px_to_string(vm, f)) == PX_EXCEPTION || !(s = px_str_flat(vm, f))) return PX_EXCEPTION;
    *bits = 0;
    for (k = 0; k < s->len; k++) {
        uint16_t ch = px_str_at(s, k);
        *bits |= ch == 'g' ? PX_RE_GLOBAL : ch == 'u' ? PX_RE_UNICODE : ch == 'y' ? PX_RE_STICKY : 0;
    }
    return f;
}

/* Whether a match is empty: native, or ToString(Get(res, "0")). -1 exception. */
static int match_empty(PxVM *vm, PxValue res, const int32_t *caps) {
    PxValue v;
    if (res == PX_UNDEFINED) return caps[1] <= caps[0];
    v = px_get_index(vm, res, 0);
    if (v == PX_EXCEPTION || (v = px_to_string(vm, v)) == PX_EXCEPTION) return -1;
    return px_str_len(v) == 0;
}

/* After an empty match of a global search: lastIndex moves one character on. */
static int step_last_index(PxVM *vm, PxValue R, PxValue S, int unicode) {
    PxIdx li;
    if (get_last_index(vm, R, &li) < 0) return -1;
    return set_last_index(vm, R, advance(vm, S, li, unicode));
}

/* [Symbol.match](string) (22.2.6.8) */
static PxValue rep_match(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    PxValue  S, res = PX_UNDEFINED, A = PX_UNDEFINED, v = PX_UNDEFINED, r = PX_EXCEPTION;
    int32_t  local[16], *caps = NULL;
    uint32_t nr = vm->nroots, fl;
    PxIdx    n = 0;
    if (!px_is_obj(t)) return not_object(vm, "[Symbol.match]");
    PX_ROOT(vm, t);
    PX_ROOT(vm, res);
    PX_ROOT(vm, A);
    PX_ROOT(vm, v);
    S = px_to_string(vm, ARG(0));
    if (S == PX_EXCEPTION) goto out;
    PX_ROOT(vm, S);
    if (get_flags(vm, t, &fl) == PX_EXCEPTION || !(caps = caps_for(vm, t, local, 16))) goto out;
    if (!(fl & PX_RE_GLOBAL)) {
        int m = regexp_exec(vm, t, S, caps, &res);
        if (m >= 0) r = m == 0 ? PX_NULL : res != PX_UNDEFINED ? res : make_result(vm, t, S, caps);
        goto out;
    }
    if (set_last_index(vm, t, 0) < 0 || (A = px_array_new(vm, 0)) == PX_EXCEPTION) goto out;
    for (;;) {
        int m = regexp_exec(vm, t, S, caps, &res), e;
        if (m < 0) goto out;
        if (m == 0) break;
        if (res == PX_UNDEFINED) v = cap_value(vm, S, caps, 0);
        else if ((v = px_get_index(vm, res, 0)) != PX_EXCEPTION) v = px_to_string(vm, v);
        if (v == PX_EXCEPTION || px_array_push(vm, A, v) < 0) goto out;
        n++;
        e = px_str_len(v) == 0;
        if (e && step_last_index(vm, t, S, (fl & PX_RE_UNICODE) != 0) < 0) goto out;
    }
    r = n == 0 ? PX_NULL : A;
out:
    if (caps) CAPS_FREE(caps, local);
    vm->nroots = nr;
    return r;
}

/* A buffer of UTF-16 code units for building results. */
typedef struct U16Buf {
    uint16_t *d;
    uint32_t  n, cap;
    int       oom;
} U16Buf;

static void ub_put(U16Buf *b, uint16_t c) {
    if (b->n == b->cap) {
        uint32_t  cap = b->cap ? b->cap * 2 : 64;
        uint16_t *n   = b->oom || cap > (1u << 28) ? NULL : (uint16_t *)realloc(b->d, cap * sizeof(uint16_t));
        if (!n) {
            b->oom = 1;
            return;
        }
        b->d   = n;
        b->cap = cap;
    }
    b->d[b->n++] = c;
}

static void ub_range(U16Buf *b, const PxString *s, uint32_t from, uint32_t to) {
    uint32_t i;
    for (i = from; i < to && i < s->len; i++) ub_put(b, px_str_at(s, i));
}

/* Appends ToString(v). */
static int ub_value(PxVM *vm, U16Buf *b, PxValue v) {
    PxString *s;
    if ((v = px_to_string(vm, v)) == PX_EXCEPTION || !(s = px_str_flat(vm, v))) return -1;
    ub_range(b, s, 0, s->len);
    return 0;
}

static PxValue ub_finish(PxVM *vm, U16Buf *b) {
    PxValue r;
    if (b->oom) {
        free(b->d);
        return px_throw_error(vm, PX_RANGE_ERROR, "string too long");
    }
    r = px_str_new_u16(vm, b->d ? b->d : (const uint16_t *)"", b->n);
    free(b->d);
    return r;
}

/* GetSubstitution (22.1.3.19.1): the replacement template with $$ $& $`
 * $' $n $nn $<name> expanded, appended to out. caps: an array of the
 * captures (strings or undefined) or undefined; groups: an object or
 * undefined. Everything passed is rooted by the caller. */
static int get_substitution(PxVM *vm, U16Buf *out, PxValue matched, PxValue S, uint32_t pos, PxValue caps,
                            PxValue groups, PxValue tmpl) {
    PxString *t = px_str_flat(vm, tmpl), *s = px_str_flat(vm, S);
    uint32_t  k, m = 0, mlen = px_str_len(matched);
    if (!t || !s) return -1;
    if (caps != PX_UNDEFINED) m = ((PxArray *)px_ptr(caps))->length;
    for (k = 0; k < t->len; k++) {
        uint16_t ch = px_str_at(t, k), d;
        if (ch != '$' || k + 1 >= t->len) {
            ub_put(out, ch);
            continue;
        }
        d = px_str_at(t, k + 1);
        if (d == '$') {
            ub_put(out, '$');
            k++;
        } else if (d == '&') {
            if (ub_value(vm, out, matched) < 0) return -1;
            k++;
        } else if (d == '`') {
            ub_range(out, s, 0, pos);
            k++;
        } else if (d == '\'') {
            ub_range(out, s, pos + mlen < s->len ? pos + mlen : s->len, s->len);
            k++;
        } else if (d >= '0' && d <= '9') {
            uint32_t idx = d - '0', digits = 1;
            if (k + 2 < t->len && is_digit(px_str_at(t, k + 2)) && idx * 10 + (px_str_at(t, k + 2) - '0') <= m) {
                idx    = idx * 10 + (px_str_at(t, k + 2) - '0');
                digits = 2;
            }
            if (idx >= 1 && idx <= m) {
                PxValue v = px_get_index(vm, caps, idx - 1);
                if (v == PX_EXCEPTION || (v != PX_UNDEFINED && ub_value(vm, out, v) < 0)) return -1;
            } else {
                ub_range(out, t, k, k + 1 + digits);
            }
            k += digits;
        } else if (d == '<') {
            uint32_t gt = k + 2;
            while (gt < t->len && px_str_at(t, gt) != '>') gt++;
            if (gt >= t->len || groups == PX_UNDEFINED) {
                ub_put(out, '$');
                ub_put(out, '<');
            } else {
                PxValue name = px_str_slice(vm, tmpl, k + 2, gt), v;
                if (name == PX_EXCEPTION || (name = px_intern(vm, name)) == PX_EXCEPTION) return -1;
                v = px_get(vm, groups, name);
                if (v == PX_EXCEPTION || (v != PX_UNDEFINED && ub_value(vm, out, v) < 0)) return -1;
                t = px_str_flat(vm, tmpl);
                s = px_str_flat(vm, S);
                k = gt - 1;
            }
            k++;
        } else {
            ub_put(out, '$');
        }
    }
    return 0;
}

/* The pieces of one match for replace: from a native match, or read from
 * an exec result in the order 22.2.6.11 step 14 reads them. */
typedef struct Piece {
    PxValue  matched, caps, groups; /* caps: array of captures */
    uint32_t pos;
} Piece;

static int piece_native(PxVM *vm, PxValue R, PxValue S, const int32_t *caps, Piece *pc) {
    uint32_t g, n = as_re(R)->ngroups;
    PxValue  all;
    pc->pos     = (uint32_t)caps[0];
    pc->matched = cap_value(vm, S, caps, 0);
    if (pc->matched == PX_EXCEPTION || (pc->caps = px_array_new(vm, n)) == PX_EXCEPTION) return -1;
    for (g = 1; g < n; g++) {
        PxValue v = cap_value(vm, S, caps, g);
        if (v == PX_EXCEPTION || px_array_push(vm, pc->caps, v) < 0) return -1;
    }
    if (as_re(R)->names == PX_UNDEFINED) return 0;
    /* groups_object reads element g for group g */
    all = px_array_new(vm, n);
    if (all == PX_EXCEPTION) return -1;
    PX_ROOT(vm, all);
    if (px_array_push(vm, all, pc->matched) < 0) goto fail;
    for (g = 1; g < n; g++)
        if (px_array_push(vm, all, px_get_index(vm, pc->caps, g - 1)) < 0) goto fail;
    pc->groups = groups_object(vm, R, all);
    px_pop_roots(vm, 1);
    return pc->groups == PX_EXCEPTION ? -1 : 0;
fail:
    px_pop_roots(vm, 1);
    return -1;
}

static int piece_object(PxVM *vm, PxValue res, PxValue S, Piece *pc) {
    PxIdx  len, n;
    double d;
    PxValue v;
    if (px_length_of(vm, res, &len) < 0) return -1;
    v = px_get_index(vm, res, 0);
    if (v == PX_EXCEPTION || (pc->matched = px_to_string(vm, v)) == PX_EXCEPTION) return -1;
    v = px_get(vm, res, vm->atom[PX_ATOM_index]);
    if (v == PX_EXCEPTION || px_to_number(vm, v, &d) < 0) return -1;
    d       = isnan(d) || d < 0 ? 0 : trunc(d);
    pc->pos = d > (double)px_str_len(S) ? px_str_len(S) : (uint32_t)d;
    if ((pc->caps = px_array_new(vm, 0)) == PX_EXCEPTION) return -1;
    for (n = 1; n < len; n++) {
        v = px_get_index(vm, res, n);
        if (v == PX_EXCEPTION || (v != PX_UNDEFINED && (v = px_to_string(vm, v)) == PX_EXCEPTION) ||
            px_array_push(vm, pc->caps, v) < 0)
            return -1;
    }
    pc->groups = px_get(vm, res, vm->atom[PX_ATOM_groups]);
    return pc->groups == PX_EXCEPTION ? -1 : 0;
}

/* The replacement of one piece, appended to out. */
static int replace_piece(PxVM *vm, U16Buf *out, Piece *pc, PxValue S, PxValue rv) {
    if (px_is_callable(rv)) {
        uint32_t n = ((PxArray *)px_ptr(pc->caps))->length, k, na = 0;
        PxVec   *args = px_vec_new(vm, n + 4);
        PxValue  av, r;
        if (!args) return -1;
        av = px_from_ptr(args);
        PX_ROOT(vm, av);
        args->items[na++] = pc->matched;
        for (k = 0; k < n; k++) {
            PxValue v = px_get_index(vm, pc->caps, k);
            if (v == PX_EXCEPTION) goto fail;
            ((PxVec *)px_ptr(av))->items[na++] = v;
        }
        r = px_number(vm, pc->pos);
        if (r == PX_EXCEPTION) goto fail;
        ((PxVec *)px_ptr(av))->items[na++] = r;
        ((PxVec *)px_ptr(av))->items[na++] = S;
        if (pc->groups != PX_UNDEFINED) ((PxVec *)px_ptr(av))->items[na++] = pc->groups;
        r = px_call(vm, rv, PX_UNDEFINED, (int)na, ((PxVec *)px_ptr(av))->items);
        if (r == PX_EXCEPTION || ub_value(vm, out, r) < 0) goto fail;
        px_pop_roots(vm, 1);
        return 0;
    fail:
        px_pop_roots(vm, 1);
        return -1;
    }
    if (pc->groups != PX_UNDEFINED && (pc->groups = px_to_object(vm, pc->groups)) == PX_EXCEPTION) return -1;
    return get_substitution(vm, out, pc->matched, S, pc->pos, pc->caps, pc->groups, rv);
}

/* [Symbol.replace](string, replaceValue) (22.2.6.11) */
static PxValue rep_replace(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    PxValue  S, rv = ARG(1), res = PX_UNDEFINED, list = PX_UNDEFINED, r = PX_EXCEPTION;
    Piece    pc  = {PX_UNDEFINED, PX_UNDEFINED, PX_UNDEFINED, 0};
    int32_t  local[16], *caps = NULL, *nat = NULL;
    uint32_t nr = vm->nroots, fl, nnat = 0, natcap = 0, ncw = 0, k, nres, next = 0;
    U16Buf   b = {0}, scratch = {0};
    if (!px_is_obj(t)) return not_object(vm, "[Symbol.replace]");
    PX_ROOT(vm, t);
    PX_ROOT(vm, rv);
    PX_ROOT(vm, res);
    PX_ROOT(vm, list);
    PX_ROOT(vm, pc.matched);
    PX_ROOT(vm, pc.caps);
    PX_ROOT(vm, pc.groups);
    S = px_to_string(vm, ARG(0));
    if (S == PX_EXCEPTION) goto out;
    PX_ROOT(vm, S);
    if (!px_is_callable(rv) && (rv = px_to_string(vm, rv)) == PX_EXCEPTION) goto out;
    if (get_flags(vm, t, &fl) == PX_EXCEPTION) goto out;
    if ((fl & PX_RE_GLOBAL) && set_last_index(vm, t, 0) < 0) goto out;
    if (!(caps = caps_for(vm, t, local, 16)) || (list = px_array_new(vm, 0)) == PX_EXCEPTION) goto out;
    if (as_re(t)) ncw = 2 * as_re(t)->ngroups;
    /* all the matches first, then the replacements (which may run code) */
    for (;;) {
        int m = regexp_exec(vm, t, S, caps, &res), e;
        if (m < 0) goto out;
        if (m == 0) break;
        if (res == PX_UNDEFINED) {
            if (nnat == natcap) {
                int32_t *nn = (int32_t *)realloc(nat, (size_t)(natcap = natcap * 2 + 4) * ncw * sizeof(int32_t));
                if (!nn) {
                    px_throw_oom(vm);
                    goto out;
                }
                nat = nn;
            }
            memcpy(nat + (size_t)nnat * ncw, caps, ncw * sizeof(int32_t));
            if (px_array_push(vm, list, px_from_smi((int32_t)nnat++)) < 0) goto out;
        } else if (px_array_push(vm, list, res) < 0) {
            goto out;
        }
        if (!(fl & PX_RE_GLOBAL)) break;
        if ((e = match_empty(vm, res, caps)) < 0) goto out;
        if (e && step_last_index(vm, t, S, (fl & PX_RE_UNICODE) != 0) < 0) goto out;
    }
    nres = ((PxArray *)px_ptr(list))->length;
    for (k = 0; k < nres; k++) {
        PxValue e = px_get_index(vm, list, k);
        U16Buf *to;
        pc.groups = PX_UNDEFINED;
        if (px_is_smi(e) ? piece_native(vm, t, S, nat + (size_t)px_smi(e) * ncw, &pc) < 0
                         : piece_object(vm, e, S, &pc) < 0)
            goto out;
        to = pc.pos >= next ? &b : &scratch;
        if (to == &b) {
            PxString *s = px_str_flat(vm, S);
            ub_range(&b, s, next, pc.pos);
        }
        if (replace_piece(vm, to, &pc, S, rv) < 0) goto out;
        if (to == &b) next = pc.pos + px_str_len(pc.matched);
        scratch.n = 0;
    }
    {
        PxString *s = px_str_flat(vm, S);
        ub_range(&b, s, next, s->len);
    }
    r   = ub_finish(vm, &b);
    b.d = NULL;
out:
    free(b.d);
    free(scratch.d);
    free(nat);
    if (caps) CAPS_FREE(caps, local);
    vm->nroots = nr;
    return r;
}

/* [Symbol.search](string) (22.2.6.12) */
static PxValue rep_search(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    PxValue  S, prev = PX_UNDEFINED, cur, res = PX_UNDEFINED, r = PX_EXCEPTION;
    int32_t  local[16], *caps = NULL;
    uint32_t nr = vm->nroots;
    int      m;
    if (!px_is_obj(t)) return not_object(vm, "[Symbol.search]");
    PX_ROOT(vm, t);
    PX_ROOT(vm, prev);
    PX_ROOT(vm, res);
    S = px_to_string(vm, ARG(0));
    if (S == PX_EXCEPTION) goto out;
    PX_ROOT(vm, S);
    prev = px_get(vm, t, vm->atom[PX_ATOM_lastIndex]);
    if (prev == PX_EXCEPTION) goto out;
    if (!px_same_value(vm, prev, px_from_smi(0)) && px_set(vm, t, vm->atom[PX_ATOM_lastIndex], px_from_smi(0)) < 0)
        goto out;
    if (!(caps = caps_for(vm, t, local, 16)) || (m = regexp_exec(vm, t, S, caps, &res)) < 0) goto out;
    cur = px_get(vm, t, vm->atom[PX_ATOM_lastIndex]);
    if (cur == PX_EXCEPTION ||
        (!px_same_value(vm, cur, prev) && px_set(vm, t, vm->atom[PX_ATOM_lastIndex], prev) < 0))
        goto out;
    r = m == 0 ? px_from_smi(-1) : res == PX_UNDEFINED ? px_from_smi(caps[0]) : px_get(vm, res, vm->atom[PX_ATOM_index]);
out:
    if (caps) CAPS_FREE(caps, local);
    vm->nroots = nr;
    return r;
}

/* Whether RegExp.prototype.exec is still the built-in method (a data
 * property: looking at it runs no code). */
static int proto_exec_builtin(PxVM *vm) {
    uint32_t attrs;
    PxValue *slot = px_own_slot(vm, (PxObject *)px_ptr(vm->protos[PX_PROTO_REGEXP]), KEY(K_EXEC), &attrs);
    return slot && !(attrs & PX_ATTR_ACCESSOR) && is_builtin_exec(*slot);
}

/* [Symbol.split](string, limit) (22.2.6.14). When the splitter is a plain
 * RegExp built by %RegExp% and exec is the built-in one, nothing can
 * observe the per-position lastIndex updates and exec calls the spec
 * describes: one native search finds the next separator instead. */
static PxValue rep_split(PxVM *vm, PxValue t, int argc, PxValue *argv) {
    PxValue   S, C, fl = PX_UNDEFINED, sp = PX_UNDEFINED, A = PX_UNDEFINED, res = PX_UNDEFINED, v = PX_UNDEFINED;
    PxValue   r = PX_EXCEPTION, args[2];
    int32_t   local[16], *caps = NULL;
    uint32_t  nr = vm->nroots, bits, lim = 0xFFFFFFFFu, size, p = 0, q = 0, g;
    int       fast, unicode, m;
    PxString *s;
    if (!px_is_obj(t)) return not_object(vm, "[Symbol.split]");
    PX_ROOT(vm, t);
    PX_ROOT(vm, fl);
    PX_ROOT(vm, sp);
    PX_ROOT(vm, A);
    PX_ROOT(vm, res);
    PX_ROOT(vm, v);
    S = px_to_string(vm, ARG(0));
    if (S == PX_EXCEPTION) goto out;
    PX_ROOT(vm, S);
    C = species_ctor(vm, t);
    if (C == PX_EXCEPTION) goto out;
    PX_ROOT(vm, C);
    if ((fl = get_flags(vm, t, &bits)) == PX_EXCEPTION) goto out;
    unicode = (bits & PX_RE_UNICODE) != 0;
    if (!(bits & PX_RE_STICKY)) {
        PxValue y = px_str_from_cstr(vm, "y");
        if (y == PX_EXCEPTION || (fl = px_str_concat(vm, fl, y)) == PX_EXCEPTION) goto out;
    }
    args[0] = t;
    args[1] = fl;
    if ((sp = px_construct(vm, C, 2, args)) == PX_EXCEPTION) goto out;
    if ((A = px_array_new(vm, 0)) == PX_EXCEPTION) goto out;
    if (ARG(1) != PX_UNDEFINED && px_to_uint32(vm, ARG(1), &lim) < 0) goto out;
    if (lim == 0) {
        r = A;
        goto out;
    }
    if (!(s = px_str_flat(vm, S)) || !(caps = caps_for(vm, sp, local, 16))) goto out;
    size = s->len;
    fast = C == vm->ctors[PX_PROTO_REGEXP] && as_re(sp) && proto_exec_builtin(vm);
    if (size == 0) {
        m = fast ? re_match(vm, as_re(sp), s, 0, 1, caps) : regexp_exec(vm, sp, S, caps, &res);
        if (m < 0 || (!m && px_array_push(vm, A, S) < 0)) goto out;
        r = A;
        goto out;
    }
    while (q < size) {
        uint32_t e, at = q;
        if (fast) {
            m = re_match(vm, as_re(sp), px_str_flat(vm, S), q, 0, caps);
            if (m < 0) goto out;
            if (!m || (uint32_t)caps[0] >= size) break;
            at = (uint32_t)caps[0];
            e  = (uint32_t)caps[1];
        } else {
            PxIdx li;
            if (set_last_index(vm, sp, q) < 0 || (m = regexp_exec(vm, sp, S, caps, &res)) < 0) goto out;
            if (!m) {
                q = (uint32_t)advance(vm, S, q, unicode);
                continue;
            }
            if (get_last_index(vm, sp, &li) < 0) goto out;
            e = li > (PxIdx)size ? size : (uint32_t)li;
        }
        if (e > size) e = size;
        if (e == p) {
            q = (uint32_t)advance(vm, S, at, unicode);
            continue;
        }
        v = px_str_slice(vm, S, p, at);
        if (v == PX_EXCEPTION || px_array_push(vm, A, v) < 0) goto out;
        if (((PxArray *)px_ptr(A))->length == lim) {
            r = A;
            goto out;
        }
        p = e;
        if (fast) {
            for (g = 1; g < as_re(sp)->ngroups; g++) {
                v = cap_value(vm, S, caps, g);
                if (v == PX_EXCEPTION || px_array_push(vm, A, v) < 0) goto out;
                if (((PxArray *)px_ptr(A))->length == lim) {
                    r = A;
                    goto out;
                }
            }
        } else {
            PxIdx n, i;
            if (res == PX_UNDEFINED && (res = make_result(vm, sp, S, caps)) == PX_EXCEPTION) goto out;
            if (px_length_of(vm, res, &n) < 0) goto out;
            for (i = 1; i < n; i++) {
                v = px_get_index(vm, res, i);
                if (v == PX_EXCEPTION || px_array_push(vm, A, v) < 0) goto out;
                if (((PxArray *)px_ptr(A))->length == lim) {
                    r = A;
                    goto out;
                }
            }
        }
        q = p;
    }
    v = px_str_slice(vm, S, p, size);
    if (v == PX_EXCEPTION || px_array_push(vm, A, v) < 0) goto out;
    r = A;
out:
    if (caps) CAPS_FREE(caps, local);
    vm->nroots = nr;
    return r;
}

