/* RegExp: a backtracking regular expression engine written for PXJS, and
 * the RegExp and String methods built on it (ECMAScript 2023).
 *
 * Patterns compile to a word-coded program; matching walks it with an
 * explicit backtrack stack. The C stack only follows the nesting of the
 * pattern (the parser, and lookarounds while matching), and that nesting
 * is bounded by RE_MAX_DEPTH. A hostile or careless pattern cannot take
 * the console down:
 *   - the backtrack stack is capped (RE_MAX_STACK entries),
 *   - the steps of one match are capped (RE_STEPS_BASE plus
 *     RE_STEPS_PER_UNIT per code unit of input: linear work always fits,
 *     exponential backtracking does not), and
 *   - the host's interrupt callback is polled while matching;
 * running out of either limit throws a RangeError.
 *
 * Everything ES2023 has is there: the flags d g i m s u y, named groups,
 * lookbehind (compiled right to left, as the spec runs it), Unicode mode
 * (code points, \u{...}, \p{...} with every property ECMAScript names,
 * simple case folding), and the Symbol.match/matchAll/replace/search/split
 * protocol with its generic paths for subclasses and RegExp-like objects.
 * The ES2024 v flag and later additions are not.
 *
 * Annex B: without the u flag, patterns follow the grammar of Annex B.1.2,
 * as every web engine does: ']' '{' '}' may stand for themselves, \8 \9
 * and unknown escapes are identity escapes, octal escapes, \c inside
 * classes (\c0 \c_), class ranges with class escapes ([\d-x]: no range),
 * a \N beyond the group count is an octal escape, and lookaheads may be
 * quantified. PXJS runs all code as strict mode code, but this grammar is
 * not about strictness: it is what existing patterns are written in. With
 * the u flag the syntax is the strict one.
 *
 * Unicode data (categories, scripts, binary properties, case mappings) is
 * in px_unicode.c, generated by tools/gen_unicode.py. */

#include <math.h>
#include <stdio.h>
#include <stdlib.h>

#include "px_internal.h"

#define ARG(i) px_arg(argc, argv, (i))

#define RE_MAX_STACK      (256 * 1024) /* backtrack entries, 12 bytes each */
#define RE_STEPS_BASE     (4u * 1000 * 1000)
#define RE_STEPS_PER_UNIT 64u
#define RE_MAX_DEPTH      256 /* nesting of groups and lookarounds */
#define RE_MAX_GROUPS     65535
#define RE_MAX_REGS       65535
#define RE_MAX_CODE       (1u << 22) /* program words */
#define RE_INF            0x7FFFFFFF /* an unbounded quantifier */
#define RE_MAX_CP         0x10FFFF
#define RE_MAX_INDEX      9007199254740991LL

/* ------------------------------------------------------------ character sets */

/* Sets of code points as [lo, hi] pairs: sorted and disjoint once
 * normalised (cs_norm). Allocation failure is sticky (oom). */
typedef struct CSet {
    uint32_t *r;
    int       n, cap, oom;
} CSet;

static void cs_add(CSet *s, uint32_t lo, uint32_t hi) {
    if (s->n == s->cap) {
        int       cap = s->cap ? s->cap * 2 : 16;
        uint32_t *r   = s->oom ? NULL : (uint32_t *)realloc(s->r, (size_t)cap * 2 * sizeof(uint32_t));
        if (!r) {
            s->oom = 1;
            return;
        }
        s->r   = r;
        s->cap = cap;
    }
    s->r[2 * s->n]     = lo;
    s->r[2 * s->n + 1] = hi;
    s->n++;
}

static void cs_append(CSet *s, const CSet *t) {
    int k;
    for (k = 0; k < t->n; k++) cs_add(s, t->r[2 * k], t->r[2 * k + 1]);
    s->oom |= t->oom;
}

static int cmp_range(const void *a, const void *b) {
    uint32_t x = *(const uint32_t *)a, y = *(const uint32_t *)b;
    return x < y ? -1 : x > y;
}

static void cs_norm(CSet *s) {
    int k, w = 0;
    if (s->n < 2) return;
    qsort(s->r, (size_t)s->n, 2 * sizeof(uint32_t), cmp_range);
    for (k = 1; k < s->n; k++) {
        if (s->r[2 * k] <= s->r[2 * w + 1] + 1) {
            if (s->r[2 * k + 1] > s->r[2 * w + 1]) s->r[2 * w + 1] = s->r[2 * k + 1];
        } else {
            w++;
            s->r[2 * w]     = s->r[2 * k];
            s->r[2 * w + 1] = s->r[2 * k + 1];
        }
    }
    s->n = w + 1;
}

/* out (empty) = a OP b, both normalised. Bit (2 * in_a + in_b) of op says
 * whether a code point is in the result: union 0xE, a minus b 0x4, xor
 * 0x6, complement of a 0x3. The code points end at max. */
static void cs_op(CSet *out, const CSet *a, const CSet *b, int op, uint32_t max) {
    int      i = 0, j = 0, ina = 0, inb = 0, in = op & 1;
    uint32_t start = 0;
    for (;;) {
        uint32_t na = i < 2 * a->n ? a->r[i] + (uint32_t)(i & 1) : UINT32_MAX;
        uint32_t nb = j < 2 * b->n ? b->r[j] + (uint32_t)(j & 1) : UINT32_MAX;
        uint32_t p  = na < nb ? na : nb;
        int      now;
        if (p > max) break;
        if (na == p) ina = !(i++ & 1);
        if (nb == p) inb = !(j++ & 1);
        now = (op >> (2 * ina + inb)) & 1;
        if (now != in) {
            if (now) start = p;
            else cs_add(out, start, p - 1);
            in = now;
        }
    }
    if (in) cs_add(out, start, max);
    out->oom |= a->oom | b->oom;
}

/* Replaces *s by (*s OP t). */
static void cs_apply(CSet *s, const CSet *t, int op, uint32_t max) {
    CSet r = {0};
    cs_op(&r, s, t, op, max);
    free(s->r);
    *s = r;
}

static int ranges_have(const uint32_t *r, int n, uint32_t c) {
    int lo = 0, hi = n;
    while (lo < hi) {
        int mid = (lo + hi) >> 1;
        if (c < r[2 * mid]) hi = mid;
        else if (c > r[2 * mid + 1]) lo = mid + 1;
        else return 1;
    }
    return 0;
}

/* ------------------------------------------------------------ Unicode data */

/* px_unicode.c; the formats are described in tools/gen_unicode.py. */
extern const char     px_ucd_gc_names[], px_ucd_sc_names[], px_ucd_bin_names[];
extern const uint32_t px_ucd_gc_masks[], px_ucd_fold[], px_ucd_upper[], px_ucd_sizes[];
extern const uint8_t  px_ucd_gc[], px_ucd_sc[], px_ucd_scx[], px_ucd_bin[];
extern const uint16_t px_ucd_bin_offs[];
enum { UCD_GC_BYTES, UCD_SC_BYTES, UCD_SCX_BYTES, UCD_NBIN, UCD_NFOLD, UCD_NUPPER };

static uint32_t ucd_num(const uint8_t **pp) {
    const uint8_t *p = *pp;
    uint32_t       v = *p++;
    if (v >= 0xC0) {
        v = ((v & 0x3F) << 16) | ((uint32_t)p[0] << 8) | p[1];
        p += 2;
    } else if (v >= 0x80) {
        v = ((v & 0x3F) << 8) | p[0];
        p++;
    }
    *pp = p;
    return v;
}

/* The index of name in a list of entries "alias,alias\0" (ended by an
 * empty entry), or -1. */
static int ucd_find(const char *tab, const char *name, size_t len) {
    int idx = 0;
    while (*tab) {
        for (;;) {
            const char *e = tab;
            while (*e && *e != ',') e++;
            if ((size_t)(e - tab) == len && memcmp(tab, name, len) == 0) return idx;
            tab = e;
            if (*tab != ',') break;
            tab++;
        }
        tab++;
        idx++;
    }
    return -1;
}

/* Runs (start delta, value) over all code points: adds those whose value
 * is id or, for id < 0, whose value's bit is set in mask. */
static void ucd_runs(CSet *s, const uint8_t *p, uint32_t size, uint32_t mask, int id) {
    const uint8_t *end   = p + size;
    uint32_t       start = 0, from = 0;
    int            was   = 0;
    while (p < end) {
        uint32_t v;
        int      in;
        start += ucd_num(&p);
        v  = *p++;
        in = id >= 0 ? (int)v == id : (int)((mask >> v) & 1);
        if (in != was) {
            if (in) from = start;
            else cs_add(s, from, start - 1);
            was = in;
        }
    }
    if (was) cs_add(s, from, RE_MAX_CP);
}

static void ucd_script_ext(CSet *out, int id) {
    CSet           sc = {0}, listed = {0}, with = {0};
    const uint8_t *p = px_ucd_scx, *end = p + px_ucd_sizes[UCD_SCX_BYTES];
    uint32_t       next = 0;
    ucd_runs(&sc, px_ucd_sc, px_ucd_sizes[UCD_SC_BYTES], 0, id);
    while (p < end) {
        uint32_t lo = next + ucd_num(&p), hi = lo + ucd_num(&p), n = *p++, k;
        int      has = 0;
        for (k = 0; k < n; k++) has |= p[k] == id;
        p += n;
        cs_add(&listed, lo, hi);
        if (has) cs_add(&with, lo, hi);
        next = hi + 1;
    }
    cs_apply(&sc, &listed, 0x4, RE_MAX_CP);
    cs_op(out, &sc, &with, 0xE, RE_MAX_CP);
    free(sc.r);
    free(listed.r);
    free(with.r);
}

/* A binary property: the symmetric difference of a base set and a range
 * list. The base is an earlier property, so the recursion is bounded by
 * the table. */
static void ucd_binary(CSet *out, int id) {
    const uint8_t *p = px_ucd_bin + px_ucd_bin_offs[id], *end = px_ucd_bin + px_ucd_bin_offs[id + 1];
    CSet           base = {0}, diff = {0};
    uint32_t       next = 0;
    int            kind = *p++;
    if (kind == 1) {
        uint32_t mask = p[0] | (uint32_t)p[1] << 8 | (uint32_t)p[2] << 16 | (uint32_t)p[3] << 24;
        p += 4;
        ucd_runs(&base, px_ucd_gc, px_ucd_sizes[UCD_GC_BYTES], mask, -1);
    } else if (kind == 2) {
        ucd_binary(&base, *p++);
    }
    while (p < end) {
        uint32_t lo = next + ucd_num(&p), hi = lo + ucd_num(&p);
        cs_add(&diff, lo, hi);
        next = hi + 1;
    }
    cs_op(out, &base, &diff, 0x6, RE_MAX_CP);
    free(base.r);
    free(diff.r);
}

/* ------------------------------------------------------------ case mapping */

/* A mapping stored as runs (start, count, stride, delta); c if unmapped. */
static uint32_t case_map(const uint32_t *tab, uint32_t n, uint32_t c) {
    uint32_t lo = 0, hi = n, w, k, stride;
    while (lo < hi) {
        uint32_t mid = (lo + hi) >> 1;
        if ((tab[2 * mid] >> 11) <= c) lo = mid + 1;
        else hi = mid;
    }
    if (lo == 0) return c;
    w      = tab[2 * (lo - 1)];
    k      = c - (w >> 11);
    stride = (w & 1) + 1;
    if (k % stride == 0 && k / stride <= ((w >> 1) & 1023)) return c + tab[2 * (lo - 1) + 1];
    return c;
}

/* Canonicalize (ECMA-262 22.2.2.7.3) for the i flag: simple case folding
 * in Unicode mode, else the uppercase mapping of the code unit (when it is
 * one code unit and does not map a non-ASCII character into ASCII). */
static uint32_t canon(uint32_t c, int u) {
    if (c < 128) {
        if (u) return c >= 'A' && c <= 'Z' ? c + 32 : c;
        return c >= 'a' && c <= 'z' ? c - 32 : c;
    }
    return u ? case_map(px_ucd_fold, px_ucd_sizes[UCD_NFOLD], c) : case_map(px_ucd_upper, px_ucd_sizes[UCD_NUPPER], c);
}

/* Adds canon(x) for every x in the (normalised) set: a character then
 * matches under the i flag iff its canonical form is in the set. */
static void case_close(CSet *s, int u) {
    const uint32_t *tab  = u ? px_ucd_fold : px_ucd_upper;
    uint32_t        runs = px_ucd_sizes[u ? UCD_NFOLD : UCD_NUPPER], k, j;
    int             n    = s->n;
    for (k = 0; k < runs; k++) {
        uint32_t w = tab[2 * k], start = w >> 11, count = ((w >> 1) & 1023) + 1, stride = (w & 1) + 1;
        for (j = 0; j < count; j++) {
            uint32_t ch = start + j * stride;
            if (ranges_have(s->r, n, ch)) cs_add(s, ch + tab[2 * k + 1], ch + tab[2 * k + 1]);
        }
    }
    cs_norm(s);
}

/* The only non-ASCII code points whose simple case folding is an ASCII
 * word character (U+017F -> s, U+212A -> k): word characters too for \w,
 * \W, \b and \B when both the u and i flags are set. */
static int is_extra_word(uint32_t c) { return c == 0x17F || c == 0x212A; }

static int is_word_ascii(uint32_t c) {
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_';
}

static int is_line_term(uint32_t c) { return c == '\n' || c == '\r' || c == 0x2028 || c == 0x2029; }

#define IS_HI(c) (((c) & 0xFC00) == 0xD800)
#define IS_LO(c) (((c) & 0xFC00) == 0xDC00)

/* ------------------------------------------------------------ the program */

/* A program is: [0] the number of loop registers, [1] the number of
 * groups (group 0 included), then the code. Offsets are relative to the
 * word holding the opcode. R_BACK on a character matcher or a
 * backreference reads right to left (inside a lookbehind). */
enum {
    R_CHAR = 1, /* c: one character (canonicalised under i) */
    R_ANY,      /* . */
    R_CLASS,    /* neg n (lo hi)*n */
    R_SPLIT,    /* a b: go to a; on failure, b */
    R_JMP,      /* off */
    R_OPEN,     /* g: a capture group starts (its position goes to a register) */
    R_CLOSE,    /* g: and ends */
    R_RESET,    /* g0 g1: groups g0..g1-1 become undefined (each loop iteration) */
    R_BOL,
    R_EOL,
    R_WORDB,
    R_NWORDB,
    R_BACKREF, /* g */
    R_LOOK,    /* neg len: a lookaround's body follows, ending in R_LOOKEND */
    R_LOOKEND,
    R_REPINIT, /* r: a loop's count register starts at 0 */
    R_REP,     /* r min max greedy exit: a loop head (min and max iterations) */
    R_SETPOS,  /* r: where an iteration started */
    R_REPEND,  /* r min head: an iteration ended; an empty one past min fails */
    R_STAR,    /* min max greedy, then a single character matcher: a loop over it */
    R_MATCH
};
#define R_BACK 0x80
/* The flag an op follows, set per op because (?ims-ims:...) changes them
 * inside a group: i on R_CHAR, R_CLASS, R_BACKREF and (with u) R_WORDB
 * R_NWORDB; s on R_ANY; m on R_BOL and R_EOL. */
#define R_FLAG 0x100
#define R_OP(w) ((w) & 0x7F)

/* ------------------------------------------------------------ compiler */

typedef struct ReC {
    const uint16_t *p;
    uint32_t        n, i;
    int32_t        *code;
    uint32_t        len, cap;
    uint32_t        flags;
    int             u, icase, back, depth;
    int             ngroups;   /* capture groups opened so far, group 0 included */
    int             total;     /* capture groups in the pattern (prescan) */
    int             has_names; /* the pattern has a named group: \k is a reference */
    int             nregs;
    uint16_t      **names; /* by group number (total + 1 entries) */
    uint32_t       *name_len;
    CSet            id_start, id_continue; /* for group names, decoded when first needed */
    const char     *error;
} ReC;

enum { ATOM_NORMAL, ATOM_SIMPLE, ATOM_ASSERT, ATOM_LOOKAHEAD };

static int re_fail(ReC *c, const char *msg) {
    if (!c->error) c->error = msg;
    return -1;
}

static int peek(ReC *c) { return c->i < c->n ? c->p[c->i] : -1; }

static int emit(ReC *c, int32_t w) {
    if (c->len == c->cap) {
        uint32_t ncap = c->cap ? c->cap * 2 : 64;
        int32_t *n    = ncap > RE_MAX_CODE ? NULL : (int32_t *)realloc(c->code, ncap * sizeof(int32_t));
        if (!n) return re_fail(c, "regular expression too large");
        c->code = n;
        c->cap  = ncap;
    }
    c->code[c->len++] = w;
    return 0;
}

/* Opens n words at `at` (for a loop head around an atom already emitted);
 * offsets are relative, so the moved code stays valid. */
static int insert(ReC *c, uint32_t at, uint32_t n) {
    uint32_t k;
    for (k = 0; k < n; k++)
        if (emit(c, 0) < 0) return -1;
    memmove(c->code + at + n, c->code + at, (c->len - n - at) * sizeof(int32_t));
    return 0;
}

static int hexval(int ch) {
    if (ch >= '0' && ch <= '9') return ch - '0';
    ch |= 0x20;
    if (ch >= 'a' && ch <= 'f') return ch - 'a' + 10;
    return -1;
}

static int is_digit(int ch) { return ch >= '0' && ch <= '9'; }

static int is_syntax_char(int ch) { return ch >= 0 && ch < 128 && strchr("^$\\.*+?()[]{}|", ch) && ch; }

/* The next pattern character; a surrogate pair is one in Unicode mode. */
static uint32_t next_char(ReC *c, int pairs) {
    uint32_t ch = c->p[c->i++];
    if (pairs && IS_HI(ch) && c->i < c->n && IS_LO(c->p[c->i]))
        ch = 0x10000 + ((ch - 0xD800) << 10) + (c->p[c->i++] - 0xDC00);
    return ch;
}

static int hex4(ReC *c) {
    int v = 0, k;
    if (c->i + 4 > c->n) return -1;
    for (k = 0; k < 4; k++) {
        int h = hexval(c->p[c->i + (uint32_t)k]);
        if (h < 0) return -1;
        v = v * 16 + h;
    }
    c->i += 4;
    return v;
}

/* After "\u": \u{...} (Unicode mode) or four hex digits, where a lead
 * surrogate escape followed by a trail surrogate escape is one code point
 * in Unicode mode. -1 (nothing consumed) if not a valid escape. */
static int32_t unicode_escape(ReC *c, int unicode) {
    uint32_t save = c->i;
    int32_t  v;
    if (unicode && peek(c) == '{') {
        uint32_t cp = 0;
        int      nd = 0;
        c->i++;
        while (hexval(peek(c)) >= 0) {
            cp = cp * 16 + (uint32_t)hexval(c->p[c->i++]);
            if (cp > RE_MAX_CP) cp = RE_MAX_CP + 1;
            nd++;
        }
        if (!nd || peek(c) != '}' || cp > RE_MAX_CP) {
            c->i = save;
            return -1;
        }
        c->i++;
        return (int32_t)cp;
    }
    v = hex4(c);
    if (v < 0) {
        c->i = save;
        return -1;
    }
    if (unicode && IS_HI(v) && c->i + 1 < c->n && c->p[c->i] == '\\' && c->p[c->i + 1] == 'u') {
        uint32_t at = c->i;
        int      t;
        c->i += 2;
        t = hex4(c);
        if (t >= 0 && IS_LO(t)) return 0x10000 + ((v - 0xD800) << 10) + (t - 0xDC00);
        c->i = at;
    }
    return v;
}

static int id_char(ReC *c, uint32_t ch, int first) {
    CSet *s = first ? &c->id_start : &c->id_continue;
    if (ch < 128) return (ch | 0x20) >= 'a' && (ch | 0x20) <= 'z' ? 1 : ch == '$' || ch == '_' || (!first && is_digit((int)ch));
    if (!first && (ch == 0x200C || ch == 0x200D)) return 1;
    if (!s->n && !s->oom) ucd_binary(s, ucd_find(px_ucd_bin_names, first ? "ID_Start" : "ID_Continue", first ? 8 : 11));
    return ranges_have(s->r, s->n, ch);
}

/* A group name, after '<' and through '>': its code units (malloc'd). The
 * name is read in Unicode mode whatever the flags (ECMA-262 22.2.1). */
static int parse_group_name(ReC *c, uint16_t **out, uint32_t *len) {
    uint16_t *buf = NULL;
    uint32_t  n = 0, cap = 0;
    *out = NULL;
    for (;;) {
        int32_t ch;
        if (c->i >= c->n) goto bad;
        if (c->p[c->i] == '>') {
            if (!n) goto bad;
            c->i++;
            break;
        }
        if (c->p[c->i] == '\\') {
            c->i++;
            if (peek(c) != 'u') goto bad;
            c->i++;
            ch = unicode_escape(c, 1);
            if (ch < 0) goto bad;
        } else {
            ch = (int32_t)next_char(c, 1);
        }
        if (!id_char(c, (uint32_t)ch, n == 0)) goto bad;
        if (n + 2 > cap) {
            uint16_t *nb = (uint16_t *)realloc(buf, (cap = cap * 2 + 16) * sizeof(uint16_t));
            if (!nb) {
                free(buf);
                return re_fail(c, "out of memory");
            }
            buf = nb;
        }
        if (ch > 0xFFFF) {
            buf[n++] = (uint16_t)(0xD800 + ((ch - 0x10000) >> 10));
            buf[n++] = (uint16_t)(0xDC00 + ((ch - 0x10000) & 0x3FF));
        } else {
            buf[n++] = (uint16_t)ch;
        }
    }
    *out = buf;
    *len = n;
    return 0;
bad:
    free(buf);
    return re_fail(c, "invalid group name");
}

/* Counts the capture groups and reads their names before parsing: \N
 * and \k<name> may refer to groups further on. */
static int prescan(ReC *c) {
    uint32_t i;
    int      in_class = 0, g = 0, k;
    for (i = 0; i < c->n; i++) {
        uint16_t ch = c->p[i];
        if (ch == '\\') i++;
        else if (in_class) in_class = ch != ']';
        else if (ch == '[') in_class = 1;
        else if (ch == '(') {
            if (i + 1 < c->n && c->p[i + 1] == '?') {
                if (i + 3 < c->n && c->p[i + 2] == '<' && c->p[i + 3] != '=' && c->p[i + 3] != '!') {
                    g++;
                    c->has_names = 1;
                }
            } else {
                g++;
            }
        }
    }
    if (g >= RE_MAX_GROUPS) return re_fail(c, "too many capture groups");
    c->total = g;
    if (!c->has_names) return 0;
    c->names    = (uint16_t **)calloc((size_t)g + 1, sizeof(uint16_t *));
    c->name_len = (uint32_t *)calloc((size_t)g + 1, sizeof(uint32_t));
    if (!c->names || !c->name_len) return re_fail(c, "out of memory");
    g = 0;
    in_class = 0;
    for (i = 0; i < c->n; i++) {
        uint16_t ch = c->p[i];
        if (ch == '\\') i++;
        else if (in_class) in_class = ch != ']';
        else if (ch == '[') in_class = 1;
        else if (ch == '(') {
            if (i + 1 < c->n && c->p[i + 1] == '?') {
                if (i + 3 < c->n && c->p[i + 2] == '<' && c->p[i + 3] != '=' && c->p[i + 3] != '!') {
                    g++;
                    c->i = i + 3;
                    if (parse_group_name(c, &c->names[g], &c->name_len[g]) < 0) return -1;
                    for (k = 1; k < g; k++)
                        if (c->names[k] && c->name_len[k] == c->name_len[g] &&
                            memcmp(c->names[k], c->names[g], c->name_len[g] * sizeof(uint16_t)) == 0)
                            return re_fail(c, "duplicate group name");
                }
            } else {
                g++;
            }
        }
    }
    c->i = 0;
    return 0;
}

static void add_escape_set(ReC *c, CSet *s, int e) {
    static const uint32_t space[] = {9,      13,     32,     32,     0xA0,   0xA0,   0x1680, 0x1680, 0x2000, 0x200A,
                                     0x2028, 0x2029, 0x202F, 0x202F, 0x205F, 0x205F, 0x3000, 0x3000, 0xFEFF, 0xFEFF};
    CSet     t = {0};
    uint32_t k;
    switch (e | 0x20) {
    case 'd': cs_add(&t, '0', '9'); break;
    case 's':
        for (k = 0; k < sizeof space / sizeof space[0]; k += 2) cs_add(&t, space[k], space[k + 1]);
        break;
    default:
        cs_add(&t, '0', '9');
        cs_add(&t, 'A', 'Z');
        cs_add(&t, '_', '_');
        cs_add(&t, 'a', 'z');
        if (c->u && c->icase) {
            cs_add(&t, 0x17F, 0x17F);
            cs_add(&t, 0x212A, 0x212A);
        }
        break;
    }
    cs_norm(&t);
    if (e < 'a') {
        CSet none = {0};
        cs_apply(&t, &none, 0x3, c->u ? RE_MAX_CP : 0xFFFF);
    }
    cs_append(s, &t);
    free(t.r);
}

/* \p{...} or \P{...}, after the p. */
static int parse_property(ReC *c, CSet *s, int negated) {
    char   buf[64];
    size_t n = 0, eq = 0;
    int    id;
    CSet   t = {0};
    if (peek(c) != '{') return re_fail(c, "invalid property name");
    c->i++;
    while (c->i < c->n && c->p[c->i] != '}') {
        uint16_t ch = c->p[c->i++];
        if (!((ch | 0x20) >= 'a' && (ch | 0x20) <= 'z') && !is_digit(ch) && ch != '_' && (ch != '=' || eq))
            return re_fail(c, "invalid property name");
        if (n + 1 >= sizeof buf) return re_fail(c, "invalid property name");
        if (ch == '=') eq = n + 1;
        buf[n++] = (char)ch;
    }
    if (c->i >= c->n) return re_fail(c, "invalid property name");
    c->i++;
    buf[n] = 0;
#define KEY_IS(k) (eq - 1 == sizeof(k) - 1 && memcmp(buf, k, sizeof(k) - 1) == 0)
    if (eq) {
        const char *val = buf + eq;
        size_t      vlen = n - eq;
        if (KEY_IS("General_Category") || KEY_IS("gc")) {
            if ((id = ucd_find(px_ucd_gc_names, val, vlen)) < 0) return re_fail(c, "invalid property name");
            ucd_runs(&t, px_ucd_gc, px_ucd_sizes[UCD_GC_BYTES], px_ucd_gc_masks[id], -1);
        } else if (KEY_IS("Script") || KEY_IS("sc")) {
            if ((id = ucd_find(px_ucd_sc_names, val, vlen)) < 0) return re_fail(c, "invalid property name");
            ucd_runs(&t, px_ucd_sc, px_ucd_sizes[UCD_SC_BYTES], 0, id);
        } else if (KEY_IS("Script_Extensions") || KEY_IS("scx")) {
            if ((id = ucd_find(px_ucd_sc_names, val, vlen)) < 0) return re_fail(c, "invalid property name");
            ucd_script_ext(&t, id);
        } else {
            return re_fail(c, "invalid property name");
        }
    } else if ((id = ucd_find(px_ucd_gc_names, buf, n)) >= 0) {
        ucd_runs(&t, px_ucd_gc, px_ucd_sizes[UCD_GC_BYTES], px_ucd_gc_masks[id], -1);
    } else if ((id = ucd_find(px_ucd_bin_names, buf, n)) >= 0) {
        ucd_binary(&t, id);
    } else {
        return re_fail(c, "invalid property name");
    }
#undef KEY_IS
    if (negated) {
        CSet none = {0};
        cs_apply(&t, &none, 0x3, RE_MAX_CP);
    }
    cs_append(s, &t);
    free(t.r);
    return 0;
}

/* Annex B LegacyOctalEscapeSequence, at its first digit. */
static uint32_t octal_escape(ReC *c) {
    uint32_t v = (uint32_t)(c->p[c->i++] - '0');
    if (peek(c) >= '0' && peek(c) <= '7') {
        uint32_t first = v;
        v = v * 8 + (uint32_t)(c->p[c->i++] - '0');
        if (first <= 3 && peek(c) >= '0' && peek(c) <= '7') v = v * 8 + (uint32_t)(c->p[c->i++] - '0');
    }
    return v;
}

/* A CharacterEscape, at the character after the backslash. */
static int char_escape(ReC *c, int in_class, uint32_t *out) {
    int e = c->p[c->i++], l;
    switch (e) {
    case 'f': *out = '\f'; return 0;
    case 'n': *out = '\n'; return 0;
    case 'r': *out = '\r'; return 0;
    case 't': *out = '\t'; return 0;
    case 'v': *out = '\v'; return 0;
    case 'c':
        l = peek(c);
        if (((l | 0x20) >= 'a' && (l | 0x20) <= 'z') || (in_class && !c->u && (is_digit(l) || l == '_'))) {
            c->i++;
            *out = (uint32_t)l % 32;
            return 0;
        }
        if (c->u) return re_fail(c, "invalid \\c escape");
        c->i--; /* Annex B: the backslash stands for itself, the c follows */
        *out = '\\';
        return 0;
    case '0':
        if (!is_digit(peek(c))) {
            *out = 0;
            return 0;
        }
        /* fallthrough */
    case '1': case '2': case '3': case '4': case '5': case '6': case '7':
        if (c->u) return re_fail(c, "invalid escape");
        c->i--;
        *out = octal_escape(c);
        return 0;
    case 'x':
        if (hexval(peek(c)) >= 0 && c->i + 1 < c->n && hexval(c->p[c->i + 1]) >= 0) {
            *out = (uint32_t)(hexval(c->p[c->i]) * 16 + hexval(c->p[c->i + 1]));
            c->i += 2;
            return 0;
        }
        break;
    case 'u': {
        int32_t v = unicode_escape(c, c->u);
        if (v >= 0) {
            *out = (uint32_t)v;
            return 0;
        }
        break;
    }
    case '-':
        if (in_class) {
            *out = '-';
            return 0;
        }
        break;
    default:
        if (c->u ? is_syntax_char(e) || e == '/' : e != 'k' || !c->has_names) {
            *out = (uint32_t)e;
            return 0;
        }
        return re_fail(c, "invalid escape");
    }
    if (c->u) return re_fail(c, "invalid escape");
    *out = (uint32_t)e; /* Annex B identity escape: \8 \9 \x \u ... */
    return 0;
}

/* Emits a class: canonicalised under the i flag (see case_close). */
static int emit_set(ReC *c, CSet *s, int neg) {
    int k;
    cs_norm(s);
    if (c->icase) case_close(s, c->u);
    if (s->oom) {
        free(s->r);
        return re_fail(c, "out of memory");
    }
    if (emit(c, R_CLASS | (c->back ? R_BACK : 0) | (c->icase ? R_FLAG : 0)) < 0 || emit(c, neg) < 0 ||
        emit(c, s->n) < 0)
        goto fail;
    for (k = 0; k < 2 * s->n; k++)
        if (emit(c, (int32_t)s->r[k]) < 0) goto fail;
    free(s->r);
    return 0;
fail:
    free(s->r);
    return -1;
}

/* One ClassAtom: a character (*ch), or a class escape added to s (*is_set). */
static int class_atom(ReC *c, CSet *s, uint32_t *ch, int *is_set) {
    int e;
    *is_set = 0;
    if (c->p[c->i] != '\\') {
        *ch = next_char(c, c->u);
        return 0;
    }
    c->i++;
    if (c->i >= c->n) return re_fail(c, "\\ at end of pattern");
    e = c->p[c->i];
    if (e == 'b') {
        c->i++;
        *ch = '\b';
        return 0;
    }
    if (strchr("dDsSwW", e) && e) {
        c->i++;
        add_escape_set(c, s, e);
        *is_set = 1;
        return 0;
    }
    if ((e == 'p' || e == 'P') && c->u) {
        c->i++;
        *is_set = 1;
        return parse_property(c, s, e == 'P');
    }
    return char_escape(c, 1, ch);
}

static int parse_class(ReC *c) {
    CSet s   = {0};
    int  neg = 0;
    c->i++;
    if (peek(c) == '^') {
        neg = 1;
        c->i++;
    }
    for (;;) {
        uint32_t lo, hi;
        int      lo_set, hi_set;
        if (c->i >= c->n) {
            free(s.r);
            return re_fail(c, "unterminated character class");
        }
        if (c->p[c->i] == ']') {
            c->i++;
            break;
        }
        if (class_atom(c, &s, &lo, &lo_set) < 0) goto fail;
        if (peek(c) == '-' && c->i + 1 < c->n && c->p[c->i + 1] != ']') {
            c->i++;
            if (class_atom(c, &s, &hi, &hi_set) < 0) goto fail;
            if (lo_set || hi_set) {
                if (c->u) {
                    re_fail(c, "invalid character class range");
                    goto fail;
                }
                /* Annex B: [\d-x] is \d, '-' and x */
                if (!lo_set) cs_add(&s, lo, lo);
                if (!hi_set) cs_add(&s, hi, hi);
                cs_add(&s, '-', '-');
                continue;
            }
            if (lo > hi) {
                re_fail(c, "range out of order in character class");
                goto fail;
            }
            cs_add(&s, lo, hi);
        } else if (!lo_set) {
            cs_add(&s, lo, lo);
        }
    }
    return emit_set(c, &s, neg);
fail:
    free(s.r);
    return -1;
}

static int emit_char(ReC *c, uint32_t ch) {
    if (emit(c, R_CHAR | (c->back ? R_BACK : 0) | (c->icase ? R_FLAG : 0)) < 0) return -1;
    return emit(c, (int32_t)(c->icase ? canon(ch, c->u) : ch));
}

/* {n}, {n,} or {n,m} at c->i: 1 (consumed), 0 (not a quantifier: nothing
 * consumed), -1 (error). */
static int parse_braces(ReC *c, uint32_t *min, uint32_t *max) {
    uint32_t save = c->i, v[2] = {0, 0};
    int      k, nd;
    c->i++;
    for (k = 0; k < 2; k++) {
        nd = 0;
        while (is_digit(peek(c))) {
            v[k] = v[k] * 10 + (uint32_t)(c->p[c->i++] - '0');
            if (v[k] > RE_INF) v[k] = RE_INF;
            nd++;
        }
        if (k == 0) {
            if (!nd) break;
            *min = *max = v[0];
            if (peek(c) == '}') {
                c->i++;
                return 1;
            }
            if (peek(c) != ',') break;
            c->i++;
        } else {
            *max = nd ? v[1] : RE_INF;
            if (peek(c) != '}') break;
            c->i++;
            if (*max < *min) return re_fail(c, "numbers out of order in {} quantifier");
            return 1;
        }
    }
    c->i = save;
    return 0;
}

static int parse_alt(ReC *c);

static int parse_group(ReC *c, int capture) {
    int g = capture ? c->ngroups++ : 0;
    if (++c->depth > RE_MAX_DEPTH) return re_fail(c, "regular expression nested too deeply");
    if (capture && (emit(c, R_OPEN) < 0 || emit(c, g) < 0)) return -1;
    if (parse_alt(c) < 0) return -1;
    if (peek(c) != ')') return re_fail(c, "unterminated group");
    c->i++;
    c->depth--;
    if (capture && (emit(c, R_CLOSE | (c->back ? R_BACK : 0)) < 0 || emit(c, g) < 0)) return -1;
    return 0;
}

/* (?= (?! (?<= (?<!: the body runs forwards or backwards from here. */
static int parse_look(ReC *c, int behind, int neg) {
    uint32_t at   = c->len;
    int      back = c->back;
    if (++c->depth > RE_MAX_DEPTH) return re_fail(c, "regular expression nested too deeply");
    if (emit(c, R_LOOK) < 0 || emit(c, neg) < 0 || emit(c, 0) < 0) return -1;
    c->back = behind;
    if (parse_alt(c) < 0) return -1;
    c->back = back;
    if (peek(c) != ')') return re_fail(c, "unterminated group");
    c->i++;
    c->depth--;
    if (emit(c, R_LOOKEND) < 0) return -1;
    c->code[at + 2] = (int32_t)(c->len - at);
    return 0;
}

/* (?ims-ims:...) (ECMAScript 2025): the flags change inside the group. */
static int parse_modifiers(ReC *c) {
    uint32_t add = 0, rem = 0, *set = &add, flags = c->flags;
    int      icase = c->icase, r;
    for (;;) {
        int      ch = peek(c);
        uint32_t bit;
        if (ch == ':') break;
        if (ch == '-' && set == &add) {
            set = &rem;
            c->i++;
            continue;
        }
        bit = ch == 'i' ? PX_RE_IGNORECASE : ch == 'm' ? PX_RE_MULTILINE : ch == 's' ? PX_RE_DOTALL : 0;
        if (!bit || ((add | rem) & bit)) return re_fail(c, "invalid group");
        *set |= bit;
        c->i++;
    }
    if (set == &rem && !add && !rem) return re_fail(c, "invalid group");
    c->i++;
    c->flags = (flags | add) & ~rem;
    c->icase = (c->flags & PX_RE_IGNORECASE) != 0;
    r        = parse_group(c, 0);
    c->flags = flags;
    c->icase = icase;
    return r;
}

/* An atom or an assertion: returns ATOM_*, or -1. */
static int parse_atom(ReC *c) {
    int      ch = peek(c), e;
    uint32_t v, min, max;
    switch (ch) {
    case '^':
    case '$':
        c->i++;
        return emit(c, (ch == '^' ? R_BOL : R_EOL) | (c->flags & PX_RE_MULTILINE ? R_FLAG : 0)) < 0 ? -1 : ATOM_ASSERT;
    case '.':
        c->i++;
        return emit(c, R_ANY | (c->back ? R_BACK : 0) | (c->flags & PX_RE_DOTALL ? R_FLAG : 0)) < 0 ? -1 : ATOM_SIMPLE;
    case '[': return parse_class(c) < 0 ? -1 : ATOM_SIMPLE;
    case '*':
    case '+':
    case '?': return re_fail(c, "nothing to repeat");
    case '{':
        if (c->u) return re_fail(c, "nothing to repeat");
        if (parse_braces(c, &min, &max) != 0) return re_fail(c, "nothing to repeat");
        break; /* Annex B: a literal { */
    case '}':
    case ']':
        if (c->u) return re_fail(c, "lone quantifier bracket");
        break;
    case '(':
        c->i++;
        if (peek(c) != '?') return parse_group(c, 1) < 0 ? -1 : ATOM_NORMAL;
        c->i++;
        e = peek(c);
        if (e == ':') {
            c->i++;
            return parse_group(c, 0) < 0 ? -1 : ATOM_NORMAL;
        }
        if (e == '=' || e == '!') {
            c->i++;
            return parse_look(c, 0, e == '!') < 0 ? -1 : ATOM_LOOKAHEAD;
        }
        if (e == '<' && c->i + 1 < c->n && (c->p[c->i + 1] == '=' || c->p[c->i + 1] == '!')) {
            c->i += 2;
            return parse_look(c, 1, c->p[c->i - 1] == '!') < 0 ? -1 : ATOM_ASSERT;
        }
        if (e == '-' || e == 'i' || e == 'm' || e == 's') return parse_modifiers(c) < 0 ? -1 : ATOM_NORMAL;
        if (e == '<') {
            /* the prescan read and checked the name */
            while (c->p[c->i] != '>') c->i++;
            c->i++;
            return parse_group(c, 1) < 0 ? -1 : ATOM_NORMAL;
        }
        return re_fail(c, "invalid group");
    case '\\':
        c->i++;
        if (c->i >= c->n) return re_fail(c, "\\ at end of pattern");
        e = c->p[c->i];
        if (e == 'b' || e == 'B') {
            c->i++;
            return emit(c, (e == 'b' ? R_WORDB : R_NWORDB) | (c->u && c->icase ? R_FLAG : 0)) < 0 ? -1 : ATOM_ASSERT;
        }
        if ((strchr("dDsSwW", e) && e) || ((e == 'p' || e == 'P') && c->u)) {
            CSet s = {0};
            c->i++;
            if (e == 'p' || e == 'P') {
                if (parse_property(c, &s, e == 'P') < 0) {
                    free(s.r);
                    return -1;
                }
            } else {
                add_escape_set(c, &s, e);
            }
            return emit_set(c, &s, 0) < 0 ? -1 : ATOM_SIMPLE;
        }
        if (e >= '1' && e <= '9') {
            uint32_t save = c->i, g = 0;
            while (is_digit(peek(c))) {
                g = g * 10 + (uint32_t)(c->p[c->i++] - '0');
                if (g > RE_MAX_GROUPS) g = RE_MAX_GROUPS;
            }
            if (g <= (uint32_t)c->total) {
                if (emit(c, R_BACKREF | (c->back ? R_BACK : 0) | (c->icase ? R_FLAG : 0)) < 0 || emit(c, (int32_t)g) < 0)
                    return -1;
                return ATOM_NORMAL;
            }
            if (c->u) return re_fail(c, "invalid backreference");
            c->i = save; /* Annex B: an octal escape, or \8 \9 */
        }
        if (e == 'k' && (c->u || c->has_names)) {
            uint16_t *name;
            uint32_t  len;
            int       g;
            c->i++;
            if (peek(c) != '<') return re_fail(c, "invalid named reference");
            c->i++;
            if (parse_group_name(c, &name, &len) < 0) return -1;
            for (g = 1; g <= c->total; g++)
                if (c->names && c->names[g] && c->name_len[g] == len &&
                    memcmp(c->names[g], name, len * sizeof(uint16_t)) == 0)
                    break;
            free(name);
            if (g > c->total) return re_fail(c, "reference to an undefined group name");
            if (emit(c, R_BACKREF | (c->back ? R_BACK : 0) | (c->icase ? R_FLAG : 0)) < 0 || emit(c, g) < 0) return -1;
            return ATOM_NORMAL;
        }
        if (char_escape(c, 0, &v) < 0) return -1;
        return emit_char(c, v) < 0 ? -1 : ATOM_SIMPLE;
    default: break;
    }
    return emit_char(c, next_char(c, c->u)) < 0 ? -1 : ATOM_SIMPLE;
}

/* Wraps code[start, len), an atom holding groups g0..ngroups-1, in a loop. */
static int quantify(ReC *c, uint32_t start, int g0, int simple, uint32_t min, uint32_t max, int greedy) {
    uint32_t head, r, at;
    int      reset = c->ngroups > g0;
    if (max == 0) {
        c->len = start; /* never runs: its groups stay undefined */
        return 0;
    }
    if (min == 1 && max == 1) return 0;
    if (simple) {
        if (insert(c, start, 4) < 0) return -1;
        c->code[start]     = R_STAR;
        c->code[start + 1] = (int32_t)min;
        c->code[start + 2] = (int32_t)max;
        c->code[start + 3] = greedy;
        return 0;
    }
    /* REPINIT r; head: REP r min max greedy exit; SETPOS r+1; [RESET g0 g1]; atom; REPEND r min head */
    if (c->nregs + 2 > RE_MAX_REGS) return re_fail(c, "regular expression too large");
    r = (uint32_t)c->nregs;
    c->nregs += 2;
    head = 2 + 6 + 2 + (reset ? 3 : 0);
    if (insert(c, start, head) < 0) return -1;
    at                 = start + 2;
    c->code[start]     = R_REPINIT;
    c->code[start + 1] = (int32_t)r;
    c->code[at]        = R_REP;
    c->code[at + 1]    = (int32_t)r;
    c->code[at + 2]    = (int32_t)min;
    c->code[at + 3]    = (int32_t)max;
    c->code[at + 4]    = greedy;
    c->code[at + 6]    = R_SETPOS;
    c->code[at + 7]    = (int32_t)r + 1;
    if (reset) {
        c->code[at + 8]  = R_RESET;
        c->code[at + 9]  = g0;
        c->code[at + 10] = c->ngroups;
    }
    head = c->len;
    if (emit(c, R_REPEND) < 0 || emit(c, (int32_t)r) < 0 || emit(c, (int32_t)min) < 0 ||
        emit(c, (int32_t)at - (int32_t)head) < 0)
        return -1;
    c->code[at + 5] = (int32_t)(c->len - at);
    return 0;
}

static int parse_term(ReC *c) {
    uint32_t start = c->len, min, max;
    int      g0 = c->ngroups, kind = parse_atom(c), greedy = 1, ch;
    if (kind < 0) return -1;
    ch = peek(c);
    if (ch == '*' || ch == '+' || ch == '?') {
        min = ch == '+';
        max = ch == '?' ? 1 : RE_INF;
        c->i++;
    } else if (ch == '{') {
        int r = parse_braces(c, &min, &max);
        if (r < 0) return -1;
        if (r == 0) return c->u ? re_fail(c, "incomplete quantifier") : 0;
    } else {
        return 0;
    }
    if (peek(c) == '?') {
        greedy = 0;
        c->i++;
    }
    if (kind == ATOM_ASSERT || (kind == ATOM_LOOKAHEAD && c->u)) return re_fail(c, "nothing to repeat");
    return quantify(c, start, g0, kind == ATOM_SIMPLE, min, max, greedy);
}

/* A sequence of terms; backwards (in a lookbehind) their code is laid out
 * in reverse order, so they match right to left. */
static int parse_seq(ReC *c) {
    uint32_t  seq = c->len, *starts = NULL, nterms = 0, cap = 0, k;
    int       r   = 0;
    for (;;) {
        int ch = peek(c);
        if (ch < 0 || ch == '|' || ch == ')') break;
        if (c->back) {
            if (nterms == cap) {
                uint32_t *ns = (uint32_t *)realloc(starts, (cap = cap * 2 + 8) * sizeof(uint32_t));
                if (!ns) {
                    r = re_fail(c, "out of memory");
                    break;
                }
                starts = ns;
            }
            starts[nterms++] = c->len;
        }
        if ((r = parse_term(c)) < 0) break;
    }
    if (r == 0 && nterms > 1) {
        int32_t *tmp = (int32_t *)malloc((c->len - seq) * sizeof(int32_t));
        uint32_t w   = 0;
        if (!tmp) {
            free(starts);
            return re_fail(c, "out of memory");
        }
        for (k = nterms; k-- > 0;) {
            uint32_t to = k + 1 < nterms ? starts[k + 1] : c->len;
            memcpy(tmp + w, c->code + starts[k], (to - starts[k]) * sizeof(int32_t));
            w += to - starts[k];
        }
        memcpy(c->code + seq, tmp, w * sizeof(int32_t));
        free(tmp);
    }
    free(starts);
    return r;
}

static int parse_alt(ReC *c) {
    uint32_t start = c->len;
    if (parse_seq(c) < 0) return -1;
    while (peek(c) == '|') {
        /* SPLIT left right; left; JMP end; right */
        uint32_t left, jmp;
        c->i++;
        left = c->len - start;
        if (insert(c, start, 3) < 0) return -1;
        c->code[start]     = R_SPLIT;
        c->code[start + 1] = 3;
        c->code[start + 2] = (int32_t)(3 + left + 2);
        jmp                = c->len;
        if (emit(c, R_JMP) < 0 || emit(c, 0) < 0) return -1;
        if (parse_seq(c) < 0) return -1;
        c->code[jmp + 1] = (int32_t)(c->len - jmp);
    }
    return 0;
}

static void rec_free(ReC *c) {
    int g;
    if (c->names)
        for (g = 0; g <= c->total; g++) free(c->names[g]);
    free(c->names);
    free(c->name_len);
    free(c->code);
    free(c->id_start.r);
    free(c->id_continue.r);
}

/* Compiles units[0, n) under flags into c (freed by rec_free): NULL, or
 * the SyntaxError's message. */
static const char *re_compile(ReC *c, const uint16_t *units, uint32_t n, uint32_t flags) {
    c->p     = units;
    c->n     = n;
    c->flags = flags;
    c->u     = (flags & PX_RE_UNICODE) != 0;
    c->icase = (flags & PX_RE_IGNORECASE) != 0;
    if (prescan(c) < 0) return c->error;
    c->ngroups = 1;
    if (emit(c, 0) == 0 && emit(c, c->total + 1) == 0 && parse_alt(c) == 0) {
        if (c->i < c->n) re_fail(c, "unmatched ')'");
        else emit(c, R_MATCH);
    }
    if (!c->error) c->code[0] = c->nregs;
    return c->error;
}

